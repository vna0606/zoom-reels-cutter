STOP_TOKENS = {"и", "в", "не", "на", "я", "это", "что", "как", "а", "но", "то", "у", "с", "по", "вот", "ну", "да",
               "же", "бы", "ли", "мы", "вы", "он", "она", "они", "так", "там", "тут", "из", "за", "к", "о", "от",
               "для", "все", "всё", "его", "ее", "их", "был", "была", "было", "быть", "есть", "тоже", "уже"}


def _tokens(text: str) -> list[str]:
    return [t for t in re.split(r"[^0-9a-zа-я-]+", _norm_text(text)) if t]


def _bigrams(tokens: list[str]) -> set[tuple[str, str]]:
    return {(a, b) for a, b in zip(tokens, tokens[1:]) if not (a in STOP_TOKENS and b in STOP_TOKENS)}


def _repeated_phrase(first: list[str], second: list[str]) -> bool:
    """Одни и те же слова встык: в хвосте первого и в начале второго (по 4 слова) общая значимая пара слов."""
    if _bigrams(first[-4:]) & _bigrams(second[:4]):
        return True
    # однословный повтор значимого слова/числа на самом шве («…тысяч. Тысяч…»)
    return bool(first and second and first[-1] == second[0] and len(first[-1]) >= 5)


def _overlaps(first: list[str], second: list[str]) -> bool:
    """Одно предложение почти целиком повторяет другое: >= 80% пар слов меньшего есть в большем."""
    x, y = _bigrams(first), _bigrams(second)
    if not x or not y:
        return False
    small, big = (x, y) if len(x) <= len(y) else (y, x)
    return len(small & big) / len(small) >= 0.8


def _opening_sentences(pieces: list[dict], sentences: list[dict], seconds: float = OPENING_SECONDS) -> list[tuple[int, int]]:
    """[(индекс куска, индекс предложения)] предложений, начинающихся в первые `seconds` секунд ролика."""
    out, t = [], 0.0
    for k, p in enumerate(pieces):
        for i in range(p["a"], p["b"] + 1):
            if t >= seconds:
                return out
            out.append((k, i))
            t += sentences[i]["end"] - sentences[i]["start"]
    return out


def _removable(pieces: list[dict], k: int, i: int) -> bool:
    p = pieces[k]
    if p["a"] == p["b"]:
        return len(pieces) > 1 and p.get("role") not in ("hook", "payoff")
    return i in (p["a"], p["b"])


def _remove_sentence(pieces: list[dict], k: int, i: int) -> list[dict]:
    pieces = [dict(p) for p in pieces]
    p = pieces[k]
    if p["a"] == p["b"]:
        del pieces[k]
    elif i == p["a"]:
        p["a"] += 1
    else:
        p["b"] -= 1
    return pieces


def _sentence_len(i: int, sentences: list[dict]) -> int:
    return len(_tokens(sentences[i]["text"]))


def _repeat_pairs(pieces: list[dict], sentences: list[dict]) -> list[tuple[tuple[int, int], tuple[int, int], str]]:
    """Пары (куски/предложения) с повтором: внутри первых 10 с и на стыках кусков."""
    pairs = []
    opening = _opening_sentences(pieces, sentences)
    for x in range(len(opening)):
        for y in range(x + 1, len(opening)):
            if _overlaps(_tokens(sentences[opening[x][1]]["text"]), _tokens(sentences[opening[y][1]]["text"])):
                pairs.append((opening[x], opening[y], "opening"))
    for k, (p, q) in enumerate(zip(pieces, pieces[1:])):
        if q["a"] == p["b"] + 1:
            continue
        a = _tokens(sentences[p["b"]]["text"])
        b = _tokens(sentences[q["a"]]["text"])
        if _repeated_phrase(a, b):
            pairs.append(((k, p["b"]), (k + 1, q["a"]), "seam"))
    return pairs


def _fix_repeats(pieces: list[dict], sentences: list[dict]) -> tuple[list[dict], list[str]]:
    """Убирает повторяющееся предложение (более короткое, если оно с краю куска). Возвращает (куски, неразрешённое)."""
    pieces = [dict(p) for p in pieces]
    for _ in range(6):
        pairs = _repeat_pairs(pieces, sentences)
        if not pairs:
            return pieces, []
        done = False
        for first, second, _kind in pairs:
            order = sorted((first, second), key=lambda ks: (_sentence_len(ks[1], sentences), -ks[0]))
            for k, i in order:
                if _removable(pieces, k, i):
                    pieces = _remove_sentence(pieces, k, i)
                    done = True
                    break
            if done:
                break
        if not done:
            break
    left = []
    for first, second, kind in _repeat_pairs(pieces, sentences):
        left.append(("повтор слов в первые 10 с: «" if kind == "opening" else "повтор слов на стыке: «")
                    + sentences[first[1]]["text"][:60] + "» / «" + sentences[second[1]]["text"][:60] + "»")
    return pieces, left


def _hook_is_fragment(pieces: list[dict], sentences: list[dict]) -> bool:
    if not pieces:
        return False
    p = pieces[0]
    return sum(_sentence_len(i, sentences) for i in range(p["a"], p["b"] + 1)) < HOOK_MIN_WORDS


def _fix_hook_fragment(pieces: list[dict], sentences: list[dict]) -> list[dict]:
    """Хук-обрывок (короче HOOK_MIN_WORDS слов) достраивается следующими предложениями записи."""
    pieces = [dict(p) for p in pieces]
    for _ in range(2):
        if not _hook_is_fragment(pieces, sentences):
            break
        p = pieces[0]
        nxt = p["b"] + 1
        if nxt >= len(sentences) or any(q["a"] <= nxt <= q["b"] for q in pieces[1:]):
            break
        p["b"] = nxt
    return _merge_adjacent(pieces)


def _opening_hint(pieces: list[dict], sentences: list[dict]) -> list[str]:
    hints = []
    if _hook_is_fragment(pieces, sentences):
        hints.append("хук — обрывок короче 4 слов: хук должен быть целым предложением (или несколькими целыми)")
    hints += _fix_repeats(pieces, sentences)[1]
    return hints


