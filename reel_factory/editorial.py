def _problem_list(d: dict, extra: list[str] | None = None) -> list[str]:
    critic = d.get("critic") or {}
    out: list[str] = []
    for key, label in (("hook_strength", "хук"), ("completeness", "полнота"), ("clarity", "ясность"),
                       ("standalone", "самодостаточность"), ("single_idea", "одна мысль")):
        val = critic.get(key)
        if val is not None and int(val) < NEAR_MISS_BELOW and not critic.get("unavailable"):
            out.append(f"оценка критика: {label} {int(val)}/10 — поднять")
    for rnd in d.get("rounds") or []:
        out += [str(x) for x in rnd.get("problems") or []]
    out += [str(x) for x in d.get("round1_problems") or []]
    out += [f"стык {si['index']} — jump: {si['note']}" for si in d.get("seams_info") or [] if si.get("verdict") == "jump"]
    out += list(d.get("problems_hint") or [])
    out += list(extra or [])
    seen, uniq = set(), []
    for x in out:
        key = _norm_text(x).strip()
        if key and key not in seen:
            seen.add(key)
            uniq.append(x)
    return uniq


def _repair_block(n: int, d: dict, ctx: dict, extra: list[str] | None) -> str:
    sentences = ctx["sentences"]
    parts = [f"=== РОЛИК {n}: {d['raw'].get('title', '')} ===",
             f"ФОРМАТ: {d['format']}", f"ТЕЗИС: {d['thesis'] or d['raw'].get('description', '')}",
             "ПРОБЛЕМЫ (обязательно исправить):"]
    parts += [f"- {x}" for x in _problem_list(d, extra)] or ["- (явных замечаний нет: проверь начало, стыки и конец)"]
    parts += ["ТЕКСТ РОЛИКА (в порядке воспроизведения):", _clip_text(d["pieces"], sentences)]
    seams = _seams(d["pieces"], sentences)
    if seams:
        parts.append("СТЫКИ:")
        for sm in seams:
            parts.append(f"Стык {sm['index']}: …{sm['from_text'][-180:]} ⟶ {sm['to_text'][:180]}… ({sm['where']})")
    else:
        parts.append("СТЫКИ: нет (один непрерывный отрезок записи)")
    window = sorted(_window_ids(d["pieces"], len(sentences)))
    if window:
        parts.append("ДОСТУПНЫЕ ПРЕДЛОЖЕНИЯ ВОКРУГ (в ролике их нет; можно добавить в pieces):")
        parts += [f"{sentences[i]['id']} {sentences[i]['text']}" for i in window]
    return "\n".join(parts)


def _repair_batch(drafts: list[dict], ctx: dict, batch_no: int, tag: str, extras: dict) -> None:
    work_dir = ctx["work_dir"]
    blocks = [_repair_block(n, d, ctx, extras.get(id(d))) for n, d in enumerate(drafts, 1)]
    task = tag if batch_no == 1 else f"{tag}_b{batch_no}"
    try:
        data = _call(ctx["llm"], ctx["provider"],
                     _repair_prompt("\n\n".join(blocks), min_d=ctx["min_d"], max_d=ctx["max_d"]),
                     REPAIR_SCHEMA, work_dir, task)
    except Exception as exc:
        for d in drafts:
            d["repair"] = {"status": "error", "error": str(exc)}
        return
    _write_json(work_dir / ("editorial_" + task + "_raw.json"), data)
    verdicts = {}
    for v in data.get("clips") or []:
        try:
            verdicts[int(v.get("clip"))] = v
        except (TypeError, ValueError):
            continue
    for n, d in enumerate(drafts, 1):
        v = verdicts.get(n)
        if v is None:
            d["repair"] = {"status": "no_answer"}
            continue
        old_pieces = [dict(p) for p in d["pieces"]]
        fixed = _apply_fix(v, d, ctx, allow_reorder=False)
        applied = fixed is not None
        if applied:
            d["pieces"] = fixed
        _refresh_hints(d, ctx)
        critic, seam_info = _parse_verdict(dict(v, verdict="pass"), d, ctx)
        if not applied:
            critic["problems"].append("правка ремонта неприменима (недопустимые id, нарушен естественный порядок, длительность или области)")
        d.setdefault("rounds", []).append(dict(critic, repair=tag))
        d["seams_info"] = seam_info
        d["soft"] = False
        changed = [(p["a"], p["b"]) for p in old_pieces] != [(p["a"], p["b"]) for p in d["pieces"]]
        d["repair"] = {"status": "applied" if applied else "unapplicable", "changed": changed, "tag": tag,
                       "addressed": [{"problem": str(x.get("problem", "")), "fix": str(x.get("fix", ""))}
                                     for x in v.get("addressed") or [] if isinstance(x, dict)]}
        _finalize_critic(d, fixed=True, ctx=ctx)
        d["critic"]["repaired"] = True
        d["critic"]["repair_status"] = d["repair"]["status"]
        d["critic"]["verdict"] = "fix"
        _apply_code_rules(d, ctx)


def _repair_round(drafts: list[dict], ctx: dict, tag: str = "repair", extras: dict | None = None) -> list[dict]:
    """Ремонт пакетами. Возвращает выживших; явные дефекты после ремонта уходят в rejected."""
    if not drafts:
        return []
    extras = extras or {}
    batches = [drafts[i:i + CRITIC_BATCH] for i in range(0, len(drafts), CRITIC_BATCH)]
    workers = int((ctx["options"] or {}).get("parallel", 1) or 1)
    _run_batches(lambda arg: _repair_batch(arg[1], ctx, arg[0], tag, extras), list(enumerate(batches, 1)), workers)
    alive = []
    for d in drafts:
        critic = d.get("critic") or {}
        title = d["raw"].get("title", "")
        if d.get("repair", {}).get("status") in {"applied", "unapplicable"}:
            defects = _hard_score_defects(critic)
            if not critic.get("seams_ok", True):
                defects.append("стык jump не снят")
            if defects:
                _log_drop(ctx, title, tag, "явный дефект после ремонта: " + ", ".join(defects), critic, draft=d)
                continue
        alive.append(d)
    return alive


