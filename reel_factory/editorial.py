ANAPHORA_FIRST = {
    "он", "она", "оно", "они", "его", "ее", "её", "их", "им", "ему", "ей", "ими", "него", "нее", "неё", "них",
    "это", "этот", "эта", "эти", "этого", "этому", "этим", "этой", "то", "тот", "та", "те", "там", "тогда", "тут",
    "сложнее", "проще", "да", "нет", "и", "а", "но", "или", "либо", "зато", "однако", "поэтому", "потому", "также",
    "кстати", "плюс", "еще", "ещё", "тоже", "дальше", "потом", "причем", "причём", "такой", "такая", "такие", "такое",
    "значит", "короче", "итак", "соответственно", "например", "вообще",
}
PRONOUNS = {"он", "она", "оно", "они", "его", "ее", "её", "их", "им", "ему", "ей", "ими", "него", "нее", "неё", "них",
            "этот", "эта", "эти", "этого", "тот", "та", "те"}
ANAPHORA_PHRASES = {("так", "вот"), ("при", "этом"), ("то", "есть"), ("а", "вот"), ("и", "вот"), ("в", "итоге")}
# для детерминированной правки входа (только расширение назад) — без слабых маркеров вроде «тут», «например»
STRICT_ANAPHORA = ANAPHORA_FIRST - {"тут", "вообще", "например", "дальше", "потом", "кстати", "значит", "короче", "итак",
                                    "тогда", "там"}
HOOK_SKIP = {"ну", "вот", "смотрите", "слушайте"}
NUMBER_WORDS = {"тысяч", "тысяча", "тысячи", "миллион", "миллиона", "миллионов", "рублей", "руб", "евро", "долларов",
                "процентов", "процента", "сто", "двести", "триста", "четыреста", "пятьсот", "процент", "человек"}


def _continuation_hook(text: str) -> bool:
    """Первая фраза опирается на предыдущую: начинается с местоимения/ответа/союза (антецедент ищет ИИ)."""
    toks = _tokens(text)
    # то, что чистка всё равно снимет с начала ролика (разминка «ну/вот/то есть», союзы «и/а/но/плюс…»), не считается
    strip = HOOK_SKIP | LEADING_HEDGES | CONTINUATION_WORDS | {"получается", "итак", "смотрите", "слушайте"}
    for _ in range(3):
        if len(toks) >= 2 and toks[0] == "то" and toks[1] == "есть":
            toks = toks[2:]
        elif toks and toks[0] in strip:
            toks = toks[1:]
        else:
            break
    if not toks:
        return False
    # личное местоимение в начале фразы («…они были под руководством…», «…почему он ко мне пришёл?»): антецедент
    # в этом же предложении проверяет ИИ (action keep), код только подозревает
    if any(t in PRONOUNS for t in toks[:6]):
        return True
    return toks[0] in ANAPHORA_FIRST or tuple(toks[:2]) in ANAPHORA_PHRASES


def _strict_continuation_hook(text: str) -> bool:
    """Первая фраза ПРЯМО опирается на предыдущую: после снимаемой разминки начинается с местоимения/ответа/союза
    («Они были под руководством…», «Да, так и есть», «Так вот, он ушёл»). В отличие от _continuation_hook, местоимение
    где-то дальше в фразе не считается."""
    toks = _tokens(text)
    strip = HOOK_SKIP | LEADING_HEDGES | CONTINUATION_WORDS | {"получается", "итак", "смотрите", "слушайте"}
    for _ in range(3):
        if len(toks) >= 2 and toks[0] == "то" and toks[1] == "есть":
            toks = toks[2:]
        elif toks and toks[0] in strip:
            toks = toks[1:]
        else:
            break
    if not toks:
        return False
    return toks[0] in STRICT_ANAPHORA or tuple(toks[:2]) in ANAPHORA_PHRASES


def _number_fragment(text: str) -> bool:
    toks = _tokens(text)
    if not toks:
        return True
    numeric = sum(1 for t in toks if any(ch.isdigit() for ch in t) or t in NUMBER_WORDS)
    return len(toks) < HOOK_CLAUSE_WORDS or numeric / len(toks) >= 0.5


def _hook_problems(pieces: list[dict], sentences: list[dict]) -> list[str]:
    if not pieces:
        return []
    first = sentences[pieces[0]["a"]]["text"]
    out = []
    if _continuation_hook(first):
        out.append("продолжение: фраза начинается с местоимения/союза/ответа («" + " ".join(first.split()[:5]) + "…»)")
    if _number_fragment(first) and not _hook_is_whole_piece_clause(pieces, sentences):
        out.append("обрывок: первая фраза короче 6 слов или состоит из чисел («" + first[:50] + "»)")
    return out


def _hook_is_whole_piece_clause(pieces: list[dict], sentences: list[dict]) -> bool:
    """Короткая первая фраза допустима, если хук-кусок целиком (несколько предложений) тянет на мысль: >= 10 слов
    и первая фраза не состоит из чисел."""
    p = pieces[0]
    words = sum(_sentence_len(i, sentences) for i in range(p["a"], p["b"] + 1))
    toks = _tokens(sentences[p["a"]]["text"])
    numeric = sum(1 for t in toks if any(ch.isdigit() for ch in t) or t in NUMBER_WORDS)
    return words >= 10 and numeric / max(1, len(toks)) < 0.5 and len(toks) >= 3


def _preceding(pieces: list[dict], sentences: list[dict], n: int = 6) -> list[int]:
    used = _clip_ids(pieces)
    first = pieces[0]["a"]
    out = []
    for i in range(first - 1, max(-1, first - 1 - n), -1):
        if i in used:
            break
        out.append(i)
    return list(reversed(out))


def _fix_opening(pieces: list[dict], sentences: list[dict], max_total: float, min_total: float = 0.0) -> list[dict]:
    """Допустимая детерминированная правка входа — расширить начало НАЗАД на предыдущие предложения записи
    (до 3 штук, не больше OPENING_MAX_PREPEND_SECONDS секунд), если ролик начинается с явного продолжения чужой фразы
    («Они были…», «Да, так и есть»), и только если после этого вход становится самостоятельным. Снятие ведущих
    предложений делают критик/ремонт/отсмотр. Ничего не берётся из других мест записи, порядок не нарушается."""
    if not pieces or not _strict_continuation_hook(sentences[pieces[0]["a"]]["text"]):
        return pieces
    used = {i for q in pieces[1:] for i in range(q["a"], q["b"] + 1)}
    first = pieces[0]
    added = 0.0
    for k in range(1, 4):
        prev = first["a"] - k
        if prev < 0 or prev in used:
            break
        added += sentences[prev]["end"] - sentences[prev]["start"]
        if added > OPENING_MAX_PREPEND_SECONDS:
            break
        trial = [dict(first, a=prev)] + [dict(q) for q in pieces[1:]]
        if not _strict_continuation_hook(sentences[trial[0]["a"]]["text"]):
            if _pieces_duration(trial, sentences) <= max_total:
                return trial
            break
    return pieces


def _gate_failures(critic: dict, options: dict | None) -> list[str]:
    limits = dict(DEFAULT_MIN_CRITIC_SCORES)
    limits.update((options or {}).get("min_critic_scores") or {})
    return [f"{k} {int(critic.get(k, 0))}<{int(v)}" for k, v in limits.items() if int(critic.get(k, 0)) < int(v)]


def _scores_of(critic: dict | None) -> dict:
    critic = critic or {}
    keys = ("hook_strength", "completeness", "clarity", "standalone", "single_idea")
    return {k: critic[k] for k in keys if k in critic}


def _log_drop(ctx: dict, title: str, stage: str, reason: str, critic: dict | None = None,
              draft: dict | None = None) -> None:
    """Фиксирует отсев. Если известен черновик (куски), он сохраняется как `rejected` и остаётся пригодным к рендеру."""
    ctx.setdefault("dropped", []).append({
        "title": title, "topic": ctx.get("topic_by_title", {}).get(title, ""), "stage": stage, "reason": reason,
        "scores": _scores_of(critic)})
    if draft is not None and draft.get("pieces"):
        if critic and not draft.get("critic"):
            draft["critic"] = dict(critic, rounds=[dict(r) for r in draft.get("rounds", [])] or [dict(critic)])
        draft["reject"] = {"stage": stage, "reason": reason, "scores": _scores_of(critic or draft.get("critic"))}
        rejected = ctx.setdefault("rejected", [])
        if not any(r is draft for r in rejected):
            rejected.append(draft)


def _refresh_hints(draft: dict, ctx: dict) -> None:
    hints = [h for h in (
        _hook_hint(draft["pieces"], ctx["sentences"]),
        _payoff_hint(draft["pieces"]),
        _enum_hint(draft["pieces"], ctx["sentences"], ctx["topics"], ctx["id_index"]),
        _ordinal_hint(draft, ctx),
    ) if h]
    hints += _opening_hint(draft["pieces"], ctx["sentences"])
    if hints:
        draft["problems_hint"] = hints
    else:
        draft.pop("problems_hint", None)


def compose_clips(transcript: dict, work_dir: Path, options: dict, *, llm=None, provider=None, progress=None) -> list[dict]:
    options = options or {}
    work_dir = Path(work_dir)
    work_dir.mkdir(parents=True, exist_ok=True)
    llm = llm or _default_llm()
    emit = progress or (lambda p, m: None)
    max_clips = int(options.get("max_clips", 0))   # 0 = все ролики (качество — по связности мысли, а не по числу)
    min_d = float(options.get("min_duration", 30))
    max_d = float(options.get("max_duration", 90))
    lo_limit = 0.6 * min_d
    words = transcript.get("words") or []

    emit(2, "Делю расшифровку на предложения")
    sentences = build_sentences(transcript)
    if not sentences:
        _write_json(work_dir / "editorial_result.json", [])
        return ClipList()
    _write_json(work_dir / "editorial_sentences.json", sentences)
    id_index = {s["id"]: i for i, s in enumerate(sentences)}

    # 1. карта тем
    emit(8, "Составляю карту тем по всей записи")
    topics = _topic_map(sentences, llm, provider, work_dir, emit)
    _write_json(work_dir / "editorial_topics.json", topics)

    ctx = {"sentences": sentences, "id_index": id_index, "topics": topics, "llm": llm, "provider": provider,
           "work_dir": work_dir, "min_d": min_d, "max_d": max_d, "lo_limit": lo_limit, "options": options,
           "words": words, "dropped": [], "audience": _audience(options)}
    return _compose_from_topics(transcript, words, ctx, max_clips, emit)


def _run_batches(fn, items: list, workers: int) -> list:
    """Применяет fn к элементам, при workers>1 — параллельно; порядок результатов сохраняется."""
    if workers <= 1 or len(items) <= 1:
        return [fn(x) for x in items]
    from concurrent.futures import ThreadPoolExecutor
    with ThreadPoolExecutor(max_workers=workers) as pool:
        return list(pool.map(fn, items))


def _all_clips_mode(options: dict, max_clips: int) -> bool:
    return bool(options.get("all_clips")) or max_clips <= 0


def _batch_view(sentences: list[dict], topics: list[dict], id_index: dict[str, int]) -> tuple[str, set[int]]:
    """Строки расшифровки только для диапазонов тем пакета (с контекстом); пропуски помечены."""
    shown: set[int] = set()
    for t in topics:
        for key in ("ranges", "items"):
            for a, b in _topic_ranges(t, key, id_index):
                shown |= set(range(max(0, a - BATCH_CONTEXT), min(len(sentences), b + BATCH_CONTEXT + 1)))
    lines, prev = [], None
    for i in sorted(shown):
        if prev is not None and i != prev + 1:
            lines.append("--- (пропуск записи) ---")
        s = sentences[i]
        lines.append(f"{s['id']} [{_fmt_ms(s['start'])}, {s['end'] - s['start']:.0f}с] {s['text']}")
        prev = i
    return "\n".join(lines), shown


def _drafts_from_raw(raw_clips: list[dict], ctx: dict, shown: set[int] | None = None) -> list[dict]:
    sentences, id_index = ctx["sentences"], ctx["id_index"]
    max_d, lo_limit = ctx["max_d"], ctx["lo_limit"]
    drafts = []
    for raw in raw_clips:
        title = str(raw.get("title", "")).strip()
        ctx.setdefault("topic_by_title", {})[title] = str(raw.get("topic", "")).strip()
        pieces = _normalize_pieces(raw.get("pieces"), id_index)
        if shown is not None:  # в режиме пакетов ролик может брать только показанные предложения
            pieces = _restrict_pieces(raw.get("pieces"), shown, sentences, id_index)
        if not pieces:
            _log_drop(ctx, title, "compose", "ни один id кусков не найден в показанной расшифровке")
            continue
        fmt = _draft_format(raw)
        raw_draft = {"raw": raw, "pieces": pieces, "format": fmt, "thesis": str(raw.get("thesis", "")).strip()}
        fitted = _fit_duration(pieces, sentences, _max_for(fmt, max_d), _hi_limit(fmt, max_d), lo_limit)
        if not fitted:
            dur = _pieces_duration(pieces, sentences)
            if fmt in LONG_FORMATS and dur > _hi_limit(fmt, max_d) and _count_regions(pieces, sentences) <= MAX_REGIONS:
                # длинный список/история: не выбрасываем, а делим на два самостоятельных ролика (_resolve_oversize)
                draft = dict(raw_draft, oversize=True)
                drafts.append(draft)
                continue
            _log_drop(ctx, title, "compose", f"длительность речи {dur:.0f} с вне допуска для {fmt}",
                      draft=raw_draft if dur >= 10 else None)
            continue
        pieces = fitted
        if _count_regions(pieces, sentences) > MAX_REGIONS:
            _log_drop(ctx, title, "compose", f"больше {MAX_REGIONS} областей записи",
                      draft=dict(raw_draft, pieces=pieces))
            continue
        draft = {"raw": raw, "pieces": pieces, "format": fmt, "thesis": str(raw.get("thesis", "")).strip()}
        _refresh_hints(draft, ctx)
        drafts.append(draft)
    return drafts


def _compose_from_topics(transcript, words, ctx, max_clips, emit):
    sentences, id_index, topics = ctx["sentences"], ctx["id_index"], ctx["topics"]
    llm, provider, work_dir = ctx["llm"], ctx["provider"], ctx["work_dir"]
    min_d, max_d, options = ctx["min_d"], ctx["max_d"], ctx["options"]
    all_mode = _all_clips_mode(options, max_clips)
    workers = int(options.get("parallel", 1) or 1)
    timings = ctx.setdefault("timings", {})
    ctx["dedupe_threshold"] = 0.5 if all_mode else 0.6

    # 2. компоновка
    emit(30, "Собираю ролики из лучших мест записи")
    started = time.monotonic()
    if all_mode:
        ordered = sorted(topics, key=lambda t: min([a for a, _ in _topic_ranges(t, "ranges", id_index)] or [10 ** 9]))
        batches = [ordered[i:i + COMPOSE_TOPIC_BATCH] for i in range(0, len(ordered), COMPOSE_TOPIC_BATCH)]

        def compose_batch(arg):
            n, batch = arg
            lines, shown = _batch_view(sentences, batch, id_index)
            note = ("ПАКЕТ ТЕМ. Тебе показаны только фрагменты записи вокруг тем этого пакета; используй только показанные id. "
                    "Для КАЖДОЙ темы пакета реши, получится ли из неё сильный самодостаточный ролик: 0, 1 или (редко) 2 "
                    "ролика (например, перечень и отдельный кейс-story из той же темы). Темы kind=list ОБЯЗАТЕЛЬНО получают "
                    "кандидата формата list. Тему без сильного ролика пропусти. В поле topic укажи название темы из карты.\n\n")
            prompt = _compose_prompt(lines, _topics_text(batch, limit=len(batch)),
                                     max_clips=len(batch) + 2, min_d=min_d, max_d=max_d, batch_note=note,
                                     audience=ctx.get("audience", ""))
            data = _call(llm, provider, prompt, COMPOSE_SCHEMA, work_dir, f"compose_b{n}")
            return data, shown

        results = _run_batches(compose_batch, list(enumerate(batches, 1)), workers)
        raw_all = []
        drafts = []
        for data, shown in results:
            raw_all.extend(data.get("clips") or [])
            drafts.extend(_drafts_from_raw(data.get("clips") or [], ctx, shown))
        _write_json(work_dir / "editorial_compose_raw.json", {"clips": raw_all})
        ask = None
    else:
        ask = max_clips * OVERGENERATE_FACTOR + 1
        prompt = _compose_prompt(_compose_lines(sentences, topics, id_index), _topics_text(topics),
                                 max_clips=ask, min_d=min_d, max_d=max_d, audience=ctx.get("audience", ""))
        composed = _call(llm, provider, prompt, COMPOSE_SCHEMA, work_dir, "compose")
        _write_json(work_dir / "editorial_compose_raw.json", composed)
        drafts = _drafts_from_raw(composed.get("clips") or [], ctx)
    timings["compose"] = round(time.monotonic() - started, 1)
    drafts = _resolve_oversize(drafts, ctx)
    before = list(drafts)
    drafts = _dedupe(drafts, ctx["dedupe_threshold"])
    for d in before:
        if d not in drafts:
            _log_drop(ctx, d["raw"].get("title", ""), "compose", "дубль: пересекается с более сильным роликом", draft=d)
    if ask is not None:
        for d in drafts[ask:]:
            _log_drop(ctx, d["raw"].get("title", ""), "compose", "сверх лимита кандидатов", draft=d)
        drafts = drafts[:ask]
    ctx["candidates_total"] = len(before)

    # 2б. пропущенные сильные моменты: один проход по всей расшифровке (цитаты, реакции на зал, живые истории)
    if options.get("coverage", True):
        emit(45, "Ищу пропущенные сильные моменты")
        started = time.monotonic()
        fresh = _coverage_pass(drafts, ctx)
        drafts = drafts + fresh
        ctx["candidates_total"] += len(fresh)
        timings["coverage"] = round(time.monotonic() - started, 1)

    # 3. критик (до двух раундов; правки критика проверяются повторно). Отсев только за явные дефекты.
    emit(55, "Критик проверяет: одна мысль, стыки, законченность")
    started = time.monotonic()
    drafts = _critique(drafts, ctx)
    timings["critique"] = round(time.monotonic() - started, 1)
    _write_json(work_dir / "editorial_after_critique.json", [
        {"title": d["raw"].get("title"), "format": d["format"], "thesis": d["thesis"], "critic": d["critic"],
         "seams": d.get("seams_info", []), "pieces": d["pieces"]} for d in drafts])

    # 3б. кодовые правила (начало куска, служебный хвост) и раунд 3: ремонт «почти прошедших»
    emit(62, "Ремонт слабых мест: начало, стыки, концовка")
    started = time.monotonic()
    for d in drafts:
        _apply_code_rules(d, ctx)
    near = [d for d in drafts if _near_miss(d.get("critic"), d)]
    ctx["repair_candidates"] = len(near)
    repaired = {id(d) for d in _repair_round(near, ctx)}
    drafts = [d for d in drafts if d not in near or id(d) in repaired]
    drafts = _window_gate(drafts, ctx, "repair")
    timings["repair"] = round(time.monotonic() - started, 1)

    # 3в. главный редактор: решение по каждому кандидату, ранг, покрытие тем, дубли, названия
    emit(68, "Главный редактор выбирает и ранжирует ролики")
    started = time.monotonic()
    drafts = _chief_editor(drafts, ctx)
    drafts = _window_gate(drafts, ctx, "chief_editor")
    for n, d in enumerate(drafts, 1):
        if d.get("chief"):
            d["chief"]["rank"] = n
    timings["chief_editor"] = round(time.monotonic() - started, 1)

    # 4. чистка слов (для отсеянных — только детерминированный минимум: ролики остаются пригодными к рендеру)
    emit(72, "Убираю слова-паразиты и оговорки")
    started = time.monotonic()
    word_cuts = _tighten(drafts, sentences, words, llm, provider, work_dir, options)
    rejected_drafts = list(ctx.get("rejected", []))
    reject_cuts = _tighten(rejected_drafts, sentences, words, llm, provider, work_dir,
                           dict(options, llm_tighten=False))
    timings["tighten"] = round(time.monotonic() - started, 1)

    # сборка итога
    emit(90, "Проверяю длительность и собираю результат")
    result: list[dict] = []
    for d, cuts_idx in zip(drafts, word_cuts):
        cand = _to_candidate(d, sentences, words, cuts_idx)
        lo, hi = _final_window(d["format"], min_d, max_d, _draft_strong(d))
        # итоговое окно строгое: если после чистки длиннее — режем context/example ещё раз (hook/payoff не трогаем)
        for _ in range(3):
            if cand["duration"] <= hi:
                break
            ratio = cand["duration"] / max(1e-6, _pieces_duration(d["pieces"], sentences))
            fitted = _trim_to_window(d["pieces"], sentences, hi / max(0.5, ratio) * 0.98, lo)
            if not fitted:
                break
            d.setdefault("window_trims", []).append({"stage": "final", "before": round(cand["duration"], 1)})
            d["pieces"] = fitted
            keep = _words_of_pieces(fitted, sentences)
            cuts_idx = [c for c in cuts_idx if any(a <= c[0] and c[1] <= b for a, b in keep)]
            cand = _to_candidate(d, sentences, words, cuts_idx)
            d["window_trims"][-1]["after"] = round(cand["duration"], 1)
        if not lo <= cand["duration"] <= hi:
            _log_drop(ctx, cand["title"], "duration",
                      f"итоговая длительность {cand['duration']:.1f} с вне окна {lo:.0f}–{hi:.0f} с "
                      f"(hook/payoff не режем, сократить context/example нечем)", d.get("critic"), draft=d)
            rejected_drafts.append(d)
            reject_cuts.append(cuts_idx)
            continue
        opening = _fix_repeats(d["pieces"], sentences)[1] + (
            ["хук — обрывок короче 4 слов"] if _hook_is_fragment(d["pieces"], sentences) else [])
        if opening:
            _log_drop(ctx, cand["title"], "opening", "рваное начало: " + "; ".join(opening)[:300],
                      d.get("critic"), draft=d)
            rejected_drafts.append(d)
            reject_cuts.append(cuts_idx)
            continue
        if d.get("window_trims"):
            cand["window_trims"] = d["window_trims"]
        result.append(cand)
    if not any(c.get("chief_editor") for c in result):
        # главред недоступен/выключен: ранжирование критика — hook_warning ниже, сумма оценок, score композитора
        result.sort(key=lambda c: (bool((c.get("critic") or {}).get("hook_warning")),
                                   -sum(_scores_of(c.get("critic")).values()), -c["score"]))
    if not all_mode:
        for c in result[max_clips:]:
            _log_drop(ctx, c["title"], "ranking", f"выжил, но не вошёл в топ-{max_clips}", c.get("critic"))
            c["reject"] = dict(ctx["dropped"][-1])
            ctx.setdefault("ranking_cut", []).append(c)
        result = result[:max_clips]
    rejected_cands = []
    for d, cuts_idx in zip(rejected_drafts, reject_cuts):
        try:
            cand = _to_candidate(d, sentences, words, cuts_idx)
        except (KeyError, ValueError, IndexError):
            continue
        cand["rejected"] = dict(d.get("reject") or {"stage": "unknown", "reason": "", "scores": {}})
        cand.pop("chief_editor", None)
        rejected_cands.append(cand)
    ranking_cut = ctx.get("ranking_cut", [])
    for c in ranking_cut:
        c["rejected"] = c.pop("reject")
        rejected_cands.append(c)
    _write_json(work_dir / "editorial_result.json", {
        "clips": result, "rejected": rejected_cands, "dropped": ctx["dropped"], "timings": timings,
        "candidates_total": ctx.get("candidates_total"), "repair_candidates": ctx.get("repair_candidates", 0),
        "chief_error": ctx.get("chief_error"), "coverage_added": ctx.get("coverage_added", 0),
        "coverage_errors": ctx.get("coverage_errors", []), "splits": ctx.get("splits", []),
        "spinoffs": ctx.get("spinoffs", []), "audience": ctx.get("audience", "")})
    emit(100, f"Готово: роликов {len(result)}, не прошли проверку {len(rejected_cands)}")
    out = ClipList(result)
    out.rejected = rejected_cands
    return out


def _payoff_hint(pieces: list[dict]) -> str | None:
    if pieces and pieces[-1].get("role") != "payoff":
        return "последний кусок не имеет роли payoff: у ролика может не быть явного вывода"
    return None


def _fit_duration(pieces, sentences, max_d, hi_limit, lo_limit):
    dur = _pieces_duration(pieces, sentences)
    if dur > hi_limit:
        pieces = _trim_to_window(pieces, sentences, hi_limit, lo_limit) or []
        dur = _pieces_duration(pieces, sentences)
    # речь после чистки станет короче, поэтому нижний порог проверяем ещё и в конце
    if not pieces or dur > hi_limit or dur < lo_limit * 0.8:
        return []
    return pieces


def _dedupe(drafts, threshold: float = 0.6):
    drafts = sorted(drafts, key=lambda d: -int(d["raw"].get("score", 0) or 0))
    kept = []
    for d in drafts:
        cov = _clip_ids(d["pieces"])
        dup = False
        for k in kept:
            kc = _clip_ids(k["pieces"])
            if cov and len(cov & kc) / len(cov) > threshold:
                dup = True
                break
        if not dup:
            kept.append(d)
    return kept


