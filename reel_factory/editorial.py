def _subdraft(parent: dict, raw: dict, ctx: dict, allowed: set[int], key: str, note: str) -> dict | None:
    """Самостоятельный ролик из части родительского: куски только из `allowed`, естественный порядок,
    длительность в допуске. `key` — split_of | spinoff_of (название родителя)."""
    sentences, id_index = ctx["sentences"], ctx["id_index"]
    pieces = _restrict_pieces(raw.get("pieces"), allowed, sentences, id_index)
    if not pieces:
        return None
    fmt = _draft_format(raw) if str(raw.get("format", "")).strip().lower() in FORMATS else parent["format"]
    strong = _draft_strong(parent)
    fitted = _fit_duration(pieces, sentences, _max_for(fmt, ctx["max_d"], strong), _hi_limit(fmt, ctx["max_d"], strong),
                           ctx["lo_limit"])
    if not fitted or _count_regions(fitted, sentences) > MAX_REGIONS:
        return None
    if _pieces_duration(fitted, sentences) < FINAL_MIN_FACTOR * ctx["min_d"] * 1.05:
        return None
    title = str(raw.get("title", "")).strip() or str(parent["raw"].get("title", ""))
    thesis = str(raw.get("thesis", "")).strip() or parent.get("thesis", "")
    new_raw = dict(parent["raw"], title=title, thesis=thesis, format=fmt, description=thesis,
                   hook_text=clean_hook_text(raw.get("hook_text"), title),
                   rationale=str(raw.get("reason") or note).strip() or note)
    draft = {"raw": new_raw, "pieces": fitted, "format": fmt, "thesis": thesis, "seams_info": [],
             key: str(parent["raw"].get("title", ""))}
    critic = dict(parent.get("critic") or {})
    if critic:
        critic["rounds"] = [dict(r) for r in critic.get("rounds") or []]
        critic["problems"] = list(critic.get("problems") or []) + [note]
        draft["critic"] = critic
    ctx.setdefault("topic_by_title", {})[title] = ctx.get("topic_by_title", {}).get(parent["raw"].get("title", ""), "")
    _refresh_seam_info(draft, ctx)
    _apply_code_rules(draft, ctx)
    _refresh_hints(draft, ctx)
    return draft


def _make_spinoff(parent: dict, raw: dict, ctx: dict) -> dict | None:
    """Спин-офф главреда: самодостаточная часть сильного длинного ролика; оба остаются в выпуске."""
    sentences = ctx["sentences"]
    draft = _subdraft(parent, raw, ctx, _clip_ids(parent["pieces"]), "spinoff_of", "спин-офф главного редактора")
    if draft is None:
        return None
    if _pieces_duration(draft["pieces"], sentences) > 0.85 * _pieces_duration(parent["pieces"], sentences):
        return None   # почти весь родительский ролик — не спин-офф, а дубль
    draft["chief"] = {"decision": "spinoff", "reason": str(raw.get("reason", "")).strip() or "спин-офф сильного ролика",
                      "rank": 0, "title_fixed": False, "original_title": "", "duplicate_of": 0,
                      "spinoff_of": str(parent["raw"].get("title", ""))}
    ctx.setdefault("spinoffs", []).append({"title": draft["raw"]["title"], "of": parent["raw"].get("title", "")})
    return draft


def _split_prompt(block: str, *, min_d: float, max_d: float, audience: str) -> str:
    return f"""Ты — редактор Reels. Ниже СИЛЬНЫЙ, но слишком длинный ролик (перечень или история): целиком он не помещается в {max_d * LONG_MAX_FACTOR:.0f} секунд речи. Не выбрасывай его — раздели на ДВА самостоятельных ролика.

{_audience_block(audience)}Правила:
- каждый ролик — своя законченная мысль: свой хук-вопрос или сильное первое предложение (начало самостоятельного предложения), своё развитие и вывод; зритель, не видевший второй, понимает первый (и наоборот);
- куски СТРОГО в хронологическом порядке записи; перестановки и вынос фраз из других мест в начало запрещены; при необходимости расширь начало НАЗАД на предыдущие предложения из окна «ДОСТУПНЫЕ ПРЕДЛОЖЕНИЯ ВОКРУГ»;
- разрезать можно только по границе предложения или пункта перечня; не режь пункт или кейс посередине;
- речь каждого ролика {min_d:.0f}–{max_d:.0f} с (допустимо до {max_d * LONG_MAX_FACTOR:.0f} с, если часть сильная и законченная);
- используй только id из текста ролика и из блока «ДОСТУПНЫЕ ПРЕДЛОЖЕНИЯ ВОКРУГ»; последний кусок каждого ролика — role payoff с выводом;
- для каждого: title (до 7 слов), thesis (одно предложение), hook_text (заголовок-титр для визуала, не больше {HOOK_TEXT_MAX_WORDS} слов), format, pieces, reason.
Верни 2 ролика (если честно делится только на один сильный — верни один). Строго JSON по схеме.

{block}
"""


def _split_deterministic(d: dict, ctx: dict) -> list[dict]:
    """Запасное деление без ИИ: по границе предложения, ближайшей к середине, где обе половины достаточно длинные,
    первая заканчивается законченным предложением, а вторая не начинается с продолжения чужой фразы."""
    sentences = ctx["sentences"]
    flat = [(i, p.get("role", "point")) for p in d["pieces"] for i in range(p["a"], p["b"] + 1)]
    durs = [sentences[i]["end"] - sentences[i]["start"] for i, _ in flat]
    total = sum(durs)
    lo = FINAL_MIN_FACTOR * ctx["min_d"] * 1.05
    best = None
    for strict in (True, False):   # сначала границы с точкой в конце, потом любые границы предложений
        best_gap, acc = None, 0.0
        for k in range(len(flat) - 1):
            acc += durs[k]
            if acc < lo or total - acc < lo:
                continue
            if _is_continuation_start(flat[k + 1][0], sentences):
                continue
            if strict and not SENTENCE_END.search(sentences[flat[k][0]]["text"].strip()):
                continue
            gap = abs(acc - total / 2)
            if best_gap is None or gap < best_gap:
                best, best_gap = k, gap
        if best is not None:
            break
    if best is None:
        return []
    title = str(d["raw"].get("title", ""))
    out = []
    for n, chunk in enumerate((flat[:best + 1], flat[best + 1:]), 1):
        runs = []
        for i, role in chunk:
            if runs and i == runs[-1]["b"] + 1:
                runs[-1]["b"] = i
            else:
                runs.append({"a": i, "b": i, "role": role})
        raw = {"title": f"{title} — часть {n}", "thesis": d.get("thesis", ""), "format": d["format"],
               "hook_text": d["raw"].get("hook_text", ""), "reason": "деление длинного ролика пополам",
               "pieces": [{"from": sentences[r["a"]]["id"], "to": sentences[r["b"]]["id"],
                           "role": ("payoff" if r is runs[-1] else r["role"])} for r in runs]}
        sub = _subdraft(d, raw, ctx, _clip_ids(d["pieces"]), "split_of", "разрезан без перепроверки критиком")
        if sub is None:
            return []
        out.append(sub)
    return out


def _split_long(d: dict, ctx: dict, stage: str = "compose") -> list[dict]:
    """Сильный список/история длиннее допустимого не выбрасывается, а делится на два самостоятельных ролика.
    ИИ предлагает деление; без ответа — детерминированное деление пополам. [] — разделить нельзя."""
    import hashlib
    sentences = ctx["sentences"]
    title = str(d["raw"].get("title", ""))
    window = sorted(_window_ids(d["pieces"], len(sentences)))
    block_lines = [f"=== РОЛИК: {title} ===", f"ФОРМАТ: {d['format']}",
                   f"ТЕЗИС: {d['thesis'] or d['raw'].get('description', '')}",
                   f"РЕЧЬ: {_pieces_duration(d['pieces'], sentences):.0f} с",
                   "ТЕКСТ РОЛИКА (в порядке записи):", _clip_text(d["pieces"], sentences)]
    if window:
        block_lines.append("ДОСТУПНЫЕ ПРЕДЛОЖЕНИЯ ВОКРУГ (в ролике их нет):")
        block_lines += [f"{sentences[i]['id']} {sentences[i]['text']}" for i in window]
    task = "split_" + hashlib.md5(title.encode("utf-8")).hexdigest()[:8]
    parts: list[dict] = []
    try:
        data = _call(ctx["llm"], ctx["provider"],
                     _split_prompt("\n".join(block_lines), min_d=ctx["min_d"], max_d=ctx["max_d"],
                                   audience=ctx.get("audience", "")),
                     SPLIT_SCHEMA, ctx["work_dir"], task)
        allowed = _clip_ids(d["pieces"]) | set(window)
        for raw in (data.get("clips") or [])[:3]:
            sub = _subdraft(d, raw, ctx, allowed, "split_of", "часть разрезанного длинного ролика")
            if sub is not None:
                parts.append(sub)
    except Exception as exc:
        ctx.setdefault("split_errors", []).append(str(exc))
    if len(parts) < 2:
        fallback = _split_deterministic(d, ctx)
        if len(fallback) == 2:
            parts = fallback
    if not parts:
        return []
    ctx.setdefault("splits", []).append({"title": title, "stage": stage,
                                         "parts": [p["raw"].get("title", "") for p in parts]})
    return parts


def _resolve_oversize(drafts: list[dict], ctx: dict) -> list[dict]:
    """Ролики list/story, которые не уложились в допуск ещё на компоновке: делим на два вместо отсева."""
    out: list[dict] = []
    for d in drafts:
        if not d.pop("oversize", False):
            out.append(d)
            continue
        parts = _split_long(d, ctx, "compose")
        if parts:
            out.extend(parts)
            continue
        dur = _pieces_duration(d["pieces"], ctx["sentences"])
        _log_drop(ctx, d["raw"].get("title", ""), "compose",
                  f"длительность речи {dur:.0f} с вне допуска для {d['format']}, разделить на два ролика не вышло", draft=d)
    return out


