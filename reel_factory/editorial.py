def _topic_map(sentences, llm, provider, work_dir, progress) -> list[dict]:
    lines = [f"{s['id']} [{_fmt_hms(s['start'])}] {s['text']}" for s in sentences]
    total = sum(len(l) + 1 for l in lines)
    topics: list[dict] = []
    if total <= MAX_CHARS_WHOLE:
        data = _call(llm, provider, _topic_prompt("\n".join(lines)), TOPIC_SCHEMA, work_dir, "topic_map")
        topics = list(data.get("topics") or [])
    else:
        chunks, cur, size = [], [], 0
        for l in lines:
            if size + len(l) > MAX_CHARS_WHOLE // 2 and cur:
                chunks.append(cur)
                cur, size = [], 0
            cur.append(l)
            size += len(l) + 1
        if cur:
            chunks.append(cur)
        for n, chunk in enumerate(chunks, 1):
            if progress:
                progress(10 + int(15 * n / len(chunks)), f"Карта тем: часть {n} из {len(chunks)}")
            part = f" Это часть {n} из {len(chunks)} длинной записи: размечай только то, что видишь, id глобальные."
            data = _call(llm, provider, _topic_prompt("\n".join(chunk), part), TOPIC_SCHEMA, work_dir, f"topic_map_{n}")
            topics.extend(data.get("topics") or [])
    topics.sort(key=lambda t: -int(t.get("strength", 0) or 0))
    return topics


def _topics_text(topics: list[dict], limit: int = 40) -> str:
    out = []
    for t in topics[:limit]:
        ranges = ", ".join(f"{r.get('from')}–{r.get('to')}" for r in t.get("ranges") or [])
        line = (f"- [{t.get('kind', 'thesis')}] {t.get('title')} (сила {t.get('strength')}): "
                f"{t.get('thesis')} | {ranges} | {t.get('appeal')}")
        items = ", ".join(f"{r.get('from')}–{r.get('to')}" for r in t.get("items") or [])
        if items:
            line += f" | пункты перечня по порядку: {items}"
        out.append(line)
    return "\n".join(out) or "(тем нет)"


def _compose_lines(sentences, topics, id_index) -> str:
    def line(s):
        return f"{s['id']} [{_fmt_ms(s['start'])}, {s['end'] - s['start']:.0f}с] {s['text']}"

    lines = [line(s) for s in sentences]
    if sum(len(l) + 1 for l in lines) <= MAX_CHARS_WHOLE:
        return "\n".join(lines)
    keep: set[int] = set()
    budget = MAX_CHARS_WHOLE
    for t in topics:
        for r in t.get("ranges") or []:
            a, b = id_index.get(str(r.get("from")).upper()), id_index.get(str(r.get("to")).upper())
            if a is None or b is None:
                continue
            if a > b:
                a, b = b, a
            add = set(range(max(0, a - 3), min(len(sentences), b + 4))) - keep
            cost = sum(len(lines[i]) + 1 for i in add)
            if cost > budget:
                continue
            budget -= cost
            keep |= add
    return "\n".join(lines[i] for i in sorted(keep))


def is_strong(critic: dict | None) -> bool:
    """Критик оценил ролик как сильный: законченность и одна мысль не ниже STRONG_MIN."""
    critic = critic or {}
    if critic.get("unavailable"):
        return False
    try:
        return int(critic.get("completeness", 0)) >= STRONG_MIN and int(critic.get("single_idea", 0)) >= STRONG_MIN
    except (TypeError, ValueError):
        return False


def _max_for(fmt: str, max_d: float, strong: bool | None = None) -> float:
    """Целевой максимум длительности формата. list/story: до max_d x 1.6, если ролик сильный (или оценки ещё нет);
    без сильной оценки: list — x 1.4, story — max_d. Остальные форматы — max_d."""
    if fmt not in LONG_FORMATS:
        return max_d
    if strong is None or strong:
        return max_d * LONG_MAX_FACTOR
    return max_d * LIST_MAX_FACTOR if fmt == "list" else max_d


def _hi_limit(fmt: str, max_d: float, strong: bool | None = None) -> float:
    """Верхний допуск для речи ДО чистки: итоговый максимум формата x PRE_TIGHTEN_SLACK."""
    return _max_for(fmt, max_d, strong) * PRE_TIGHTEN_SLACK


def _final_window(fmt: str, min_d: float, max_d: float, strong: bool | None = None) -> tuple[float, float]:
    return FINAL_MIN_FACTOR * min_d, _max_for(fmt, max_d, strong) * FINAL_OVERFLOW_TOLERANCE


def final_cap(fmt: str, max_d: float, critic: dict | None) -> float:
    """Верхняя граница итоговой длительности (без допуска) для кандидата с известными оценками критика.
    Без оценок критика (ручной/старый кандидат) — как для сильного: не режем то, что нечем проверить."""
    has_scores = bool(critic) and any(k in critic for k in CONTENT_SCORES)
    return _max_for(fmt, max_d, is_strong(critic) if has_scores else None)


def _draft_strong(d: dict) -> bool | None:
    """Сильный ли ролик по последним оценкам критика; None — оценок ещё нет (до критика)."""
    critic = d.get("critic")
    if not critic or not any(k in critic for k in CONTENT_SCORES):
        rounds = d.get("rounds") or []
        critic = rounds[-1] if rounds else None
    if not critic or not any(k in critic for k in CONTENT_SCORES):
        return None
    return is_strong(critic)


def _draft_hi(d: dict, ctx: dict) -> float:
    return _hi_limit(d["format"], ctx["max_d"], _draft_strong(d))


def _draft_format(raw: dict) -> str:
    fmt = str(raw.get("format", "")).strip().lower()
    return fmt if fmt in FORMATS else "thesis"


def _norm_text(text: str) -> str:
    return str(text).lower().replace("ё", "е")


def _clip_ids(pieces: list[dict]) -> set[int]:
    return {i for p in pieces for i in range(p["a"], p["b"] + 1)}


def _count_regions(pieces: list[dict], sentences: list[dict], gap: float = REGION_GAP_SECONDS) -> int:
    spans = sorted((sentences[p["a"]]["start"], sentences[p["b"]]["end"]) for p in pieces)
    regions, current_end = 0, None
    for start, end in spans:
        if current_end is None or start - current_end > gap:
            regions += 1
            current_end = end
        else:
            current_end = max(current_end, end)
    return regions


def _seams(pieces: list[dict], sentences: list[dict]) -> list[dict]:
    """Переходы между кусками в порядке воспроизведения."""
    out = []
    for n, (p, q) in enumerate(zip(pieces, pieces[1:]), 1):
        a, b = sentences[p["b"]], sentences[q["a"]]
        delta = (b["start"] - a["end"]) / 60.0
        if q["a"] == p["b"] + 1:
            where = "подряд в записи"
        elif delta >= 0:
            where = f"в записи позже на {delta:.0f} мин"
        else:
            where = f"в записи раньше на {abs(delta):.0f} мин"
        out.append({"index": n, "from_sentence": a["id"], "to_sentence": b["id"],
                    "from_text": a["text"], "to_text": b["text"], "where": where})
    return out


def _topic_ranges(topic: dict, key: str, id_index: dict[str, int]) -> list[tuple[int, int]]:
    out = []
    for r in topic.get(key) or []:
        a, b = id_index.get(str(r.get("from", "")).strip().upper()), id_index.get(str(r.get("to", "")).strip().upper())
        if a is None or b is None:
            continue
        out.append((min(a, b), max(a, b)))
    return out


def _enum_hint(pieces: list[dict], sentences: list[dict], topics: list[dict], id_index: dict[str, int]) -> str | None:
    """Если ролик начал перечень, а дальше в источнике (в той же теме) есть пункты, которых в нём нет."""
    ids = _clip_ids(pieces)
    starts = [i for i in ids if ORDINAL_START.search(_norm_text(sentences[i]["text"]))]
    missing: list[int] = []
    for t in topics or []:
        if t.get("kind") == "list":
            items = _topic_ranges(t, "items", id_index)
            hit = [it for it in items if any(i in ids for i in range(it[0], it[1] + 1))]
            if hit and len(hit) < len(items):
                missing += [it[0] for it in items if it not in hit]
        if starts:
            for a, b in _topic_ranges(t, "ranges", id_index):
                inside = [i for i in starts if a <= i <= b]
                if not inside:
                    continue
                first = min(inside)
                missing += [i for i in range(first + 1, b + 1)
                            if i not in ids and ORDINAL_LATER.search(_norm_text(sentences[i]["text"]))]
    missing = sorted(set(missing))
    if not missing:
        return None
    shown = ", ".join(sentences[i]["id"] for i in missing[:6])
    return f"перечень оборван: в источнике дальше есть пункты ({shown}), которых нет в ролике"


def _hedge_start(text: str) -> bool:
    tokens = [t for t in re.split(r"[^0-9a-zа-я-]+", _norm_text(text)) if t][:6]
    if not tokens:
        return False
    return tokens[0] in HEDGE_FIRST_WORDS or bool(HEDGE_PHRASES.search(" ".join(tokens)))


def _hook_hint(pieces: list[dict], sentences: list[dict]) -> str | None:
    if not pieces:
        return None
    first = sentences[pieces[0]["a"]]["text"]
    if _hedge_start(first):
        return ("слабый вход: ролик начинается с разминки/оговорки («" + " ".join(first.split()[:6]) +
                "…»); верни fix: поставь первой самую сильную одну фразу (утверждение, вопрос, цифра) из материала самого ролика или из окна вокруг")
    return None


def _clip_ordinals(pieces: list[dict], sentences: list[dict], words: list[dict]) -> list[tuple[int, int]]:
    """[(индекс слова, номер)] порядковых слов ролика в порядке воспроизведения."""
    out = []
    for p in pieces:
        w0, w1 = sentences[p["a"]]["w0"], sentences[p["b"]]["w1"]
        if w0 < 0 or not words:
            continue
        for i in range(w0, w1 + 1):
            n = ORDINAL_WORDS.get(_norm_token(words[i].get("text", "")))
            if n:
                out.append((i, n))
    return out


def _ordinal_conflicts(ordinals: list[tuple[int, int]]) -> list[int]:
    """Индексы слов, которые нарушают последовательность 1, 2, 3… (повторы, пропуски, не с «первого»)."""
    expected, bad = 1, []
    for idx, n in ordinals:
        if n == expected:
            expected += 1
        else:
            bad.append(idx)
    return bad


def _ordinal_hint(draft: dict, ctx: dict) -> str | None:
    if draft.get("format") != "list":
        return None
    words = ctx.get("words") or []
    ords = _clip_ordinals(draft["pieces"], ctx["sentences"], words)
    bad = _ordinal_conflicts(ords)
    if not bad:
        return None
    shown = ", ".join(str(words[i].get("text")) for i in bad)
    return f"порядковые слова в перечне непоследовательны (конфликтуют: {shown}); чистка удалит их"



