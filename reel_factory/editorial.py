def _fmt_hms(t: float) -> str:
    t = max(0, int(t))
    return f"{t // 3600:02d}:{t % 3600 // 60:02d}:{t % 60:02d}"


def _fmt_ms(t: float) -> str:
    t = max(0, int(t))
    return f"{t // 60:02d}:{t % 60:02d}"


def build_sentences(transcript: dict, *, max_words: int = 45, pause_split: float = 1.2) -> list[dict]:
    """Режет транскрипт на предложения: [{"id","start","end","text","w0","w1"}].

    Очищенный "text" слов Reel Factory без пунктуации (pipeline.clean_word), поэтому берётся
    "raw" (исходный токен Whisper) — из него видны границы предложений. Если "raw" нет
    (старые транскрипты), границы определяются по границам сегментов и паузам.
    """
    words = transcript.get("words") or []
    segments = transcript.get("segments") or []

    if not words:
        sentences = []
        for seg in segments:
            text = str(seg.get("text", "")).strip()
            if not text:
                continue
            sentences.append({"start": float(seg["start"]), "end": float(seg["end"]), "text": text, "w0": -1, "w1": -1})
        return _number(sentences)

    starts = [float(w["start"]) for w in words]
    ends = [float(w["end"]) for w in words]
    # "raw" — исходный токен Whisper с пунктуацией (pipeline добавляет его рядом с очищенным "text")
    texts = [str(w.get("raw") or w.get("text", "")) for w in words]

    seg_starts = [float(s["start"]) for s in segments]
    seg_terminal = [bool(SENTENCE_END.search(str(s.get("text", "")).strip())) for s in segments]
    any_terminal = any(seg_terminal)

    def seg_of(i: int) -> int:
        if not segments:
            return 0
        mid = (starts[i] + ends[i]) / 2.0
        return max(0, bisect.bisect_right(seg_starts, mid) - 1)

    word_seg = [seg_of(i) for i in range(len(words))]

    ranges: list[tuple[int, int]] = []
    first = 0
    for i in range(len(words) - 1):
        gap = starts[i + 1] - ends[i]
        split = False
        if SENTENCE_END.search(texts[i].strip()):
            split = True
        elif gap >= pause_split:
            split = True
        elif segments and word_seg[i] != word_seg[i + 1]:
            si = word_seg[i]
            if seg_terminal[si] or not any_terminal or gap >= 0.5:
                split = True
        if split:
            ranges.append((first, i))
            first = i + 1
    ranges.append((first, len(words) - 1))

    final: list[tuple[int, int]] = []
    for a, b in ranges:
        final.extend(_cap_range(a, b, starts, ends, max_words))

    sentences = []
    for a, b in final:
        sentences.append({
            "start": starts[a],
            "end": ends[b],
            "text": " ".join(t.strip() for t in texts[a:b + 1]).strip(),
            "w0": a,
            "w1": b,
        })
    return _number(sentences)


def _cap_range(a: int, b: int, starts: list[float], ends: list[float], max_words: int) -> list[tuple[int, int]]:
    if b - a + 1 <= max_words:
        return [(a, b)]
    margin = max(2, min(5, (b - a + 1) // 4))
    best, best_gap = None, -1.0
    for i in range(a + margin - 1, b - margin + 1):
        gap = starts[i + 1] - ends[i]
        if gap > best_gap:
            best, best_gap = i, gap
    if best is None:
        best = (a + b) // 2
    return _cap_range(a, best, starts, ends, max_words) + _cap_range(best + 1, b, starts, ends, max_words)


def _number(sentences: list[dict]) -> list[dict]:
    for n, s in enumerate(sentences, 1):
        s["id"] = f"S{n:04d}"
    return [{"id": s["id"], "start": s["start"], "end": s["end"], "text": s["text"], "w0": s["w0"], "w1": s["w1"]}
            for s in sentences]


