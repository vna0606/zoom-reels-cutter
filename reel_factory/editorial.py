def _coverage_prompt(lines: str, covered_text: str, *, min_d: float, max_d: float, audience: str,
                     part_note: str = "") -> str:
    return f"""Ты — сильный редактор Reels. Из длинного эфира уже собраны ролики, но компоновка шла по карте тем и пропускает яркие штучные моменты. Твоя задача — найти в расшифровке СИЛЬНЫЕ САМОСТОЯТЕЛЬНЫЕ МОМЕНТЫ, которые не покрыты ни одним из уже собранных роликов, и собрать вокруг каждого новый ролик.{part_note}

{_audience_block(audience)}Что искать (поле moment):
- quote — яркая цитата, образная формулировка, афоризм;
- audience — комментарий или вопрос из зала/чата, на который спикер реагирует (например, «меня даже за еду сейчас работать не берут»), вместе с его реакцией и выводом;
- story — живая личная история или кейс (с героем, ситуацией и итогом), даже если она не «вирусная»: живые истории и кейсы ценны сами по себе;
- claim — резкое утверждение с цифрами или фактом.

Формат расшифровки: `S0123 [мм:сс, длительность] текст`; строка с «·» в начале уже входит в какой-то собранный ролик, без «·» — не покрыта. Новые ролики должны опираться в основном на НЕпокрытые предложения (покрытые допустимы только как короткий контекст).

Уже собранные ролики (темы, чтобы не дублировать):
{covered_text}

Правила:
- куски СТРОГО в хронологическом порядке записи; нельзя выносить фразу из другого места в начало; допустим только поздний возврат к той же мысли;
- ролик самодостаточен: понятен зрителю, не видевшему эфир; начинается с начала самостоятельного предложения (если нужно — расширь начало НАЗАД на предыдущие предложения); заканчивается законченным выводом (последний кусок role payoff);
- речь ролика {min_d:.0f}–{max_d:.0f} с (для list и story допустимо до {max_d * LONG_MAX_FACTOR:.0f} с); не бери приветствия, проверку связи, рекламу, организационные вопросы;
- title — до 7 слов, thesis — одно предложение, format из enum, hook_text — заголовок-титр для визуала (не больше {HOOK_TEXT_MAX_WORDS} слов, не озвучивается), description, score 0–100, rationale — почему этот момент стоит ролика, topic — короткое название темы;
- качество важнее количества: нет сильных пропущенных моментов — верни пустой список. Используй только id из расшифровки. Строго JSON по схеме.

РАСШИФРОВКА:
{lines}
"""


def _coverage_pass(drafts: list[dict], ctx: dict) -> list[dict]:
    """Один проход ИИ (на длинной записи — по частям) по ВСЕЙ расшифровке: сильные самостоятельные моменты,
    не покрытые ни одним кандидатом (цитаты, реакции на комментарии зала, живые истории, резкие утверждения с цифрами).
    Возвращает НОВЫЕ черновики (естественный порядок); дальше они идут в критик наравне с остальными."""
    sentences = ctx["sentences"]
    covered: set[int] = set()
    for d in drafts:
        covered |= _clip_ids(d["pieces"])

    def line(i):
        s = sentences[i]
        return f"{'· ' if i in covered else ''}{s['id']} [{_fmt_ms(s['start'])}, {s['end'] - s['start']:.0f}с] {s['text']}"

    titles = []
    for d in drafts[:80]:
        ids = sorted(_clip_ids(d["pieces"]))
        if ids:
            titles.append(f"- {d['raw'].get('title', '')} ({sentences[ids[0]]['id']}–{sentences[ids[-1]]['id']})")
    covered_text = "\n".join(titles) or "(пока нет)"

    chunks: list[list[int]] = []
    cur: list[int] = []
    size = 0
    limit = MAX_CHARS_WHOLE // 2
    total = sum(len(line(i)) + 1 for i in range(len(sentences)))
    if total <= MAX_CHARS_WHOLE:
        chunks = [list(range(len(sentences)))]
    else:
        for i in range(len(sentences)):
            ln = len(line(i)) + 1
            if size + ln > limit and cur:
                chunks.append(cur)
                cur = cur[-20:]   # небольшое перекрытие частей
                size = sum(len(line(k)) + 1 for k in cur)
            cur.append(i)
            size += ln
        if cur:
            chunks.append(cur)

    def run(arg):
        n, chunk = arg
        note = f" Это часть {n} из {len(chunks)} длинной записи: используй только показанные id." if len(chunks) > 1 else ""
        prompt = _coverage_prompt("\n".join(line(i) for i in chunk), covered_text, min_d=ctx["min_d"], max_d=ctx["max_d"],
                                  audience=ctx.get("audience", ""), part_note=note)
        task = "coverage" if n == 1 else f"coverage_b{n}"
        try:
            data = _call(ctx["llm"], ctx["provider"], prompt, COVERAGE_SCHEMA, ctx["work_dir"], task)
        except Exception as exc:
            ctx.setdefault("coverage_errors", []).append(str(exc))
            return [], set(chunk)
        _write_json(ctx["work_dir"] / f"editorial_{task}_raw.json", data)
        return list(data.get("clips") or []), set(chunk)

    results = _run_batches(run, list(enumerate(chunks, 1)), int((ctx["options"] or {}).get("parallel", 1) or 1))
    fresh: list[dict] = []
    for raw_clips, shown in results:
        for new in _drafts_from_raw(raw_clips, ctx, shown):
            new["source"] = "coverage"
            fresh.append(new)
    fresh = _resolve_oversize(fresh, ctx)
    before = list(fresh)
    fresh = _dedupe(fresh, ctx.get("dedupe_threshold", 0.6))
    out = []
    for d in before:
        if d not in fresh:
            _log_drop(ctx, d["raw"].get("title", ""), "compose", "дубль: пересекается с другим пропущенным моментом", draft=d)
            continue
        ids = _clip_ids(d["pieces"])
        if ids and len(ids & covered) / len(ids) > 0.5:
            _log_drop(ctx, d["raw"].get("title", ""), "compose", "пропущенный момент уже покрыт другим роликом", draft=d)
            continue
        out.append(d)
    ctx["coverage_added"] = len(out)
    return out


