def _first_tokens(text: str, n: int = 3) -> list[str]:
    return [t for t in re.split(r"[^0-9a-zа-я-]+", _norm_text(text)) if t][:n]


def _is_continuation_start(i: int, sentences: list[dict]) -> bool:
    """Предложение продолжает чужую фразу: начинается с «и/а/но/плюс/то есть…» (после возможной разминки
    «вот, ну») или это строчный обрывок предложения, разрезанного паузой/лимитом длины (предыдущее предложение
    не закончено точкой)."""
    text = sentences[i]["text"].strip()
    tokens = _first_tokens(text, 5)
    skipped = 0
    while tokens and tokens[0] in HEDGE_TOKENS and skipped < 2:   # «вот, плюс опять же…» -> смотрим на «плюс»
        tokens = tokens[1:]
        skipped += 1
    if not tokens:
        return False
    if tokens[0] in CONTINUATION_WORDS or " ".join(tokens[:2]) in CONTINUATION_PHRASES:
        return True
    if i > 0 and text[:1].islower() and _first_tokens(text, 1)[:1] != [] and _first_tokens(text, 1)[0] not in HEDGE_TOKENS:
        prev = sentences[i - 1]
        return not SENTENCE_END.search(prev["text"].strip()) and sentences[i]["start"] - prev["end"] < 6.0
    return False


def _merge_adjacent(pieces: list[dict]) -> list[dict]:
    merged: list[dict] = []
    for p in pieces:
        if merged and p["a"] <= merged[-1]["b"] + 1 and p["a"] >= merged[-1]["a"]:
            merged[-1]["b"] = max(merged[-1]["b"], p["b"])
            if p.get("role") == "payoff":
                merged[-1]["role"] = "payoff"
        else:
            merged.append(dict(p))
    return merged


def _fix_piece_starts(pieces: list[dict], sentences: list[dict], max_total: float,
                      min_total: float = 0.0) -> list[dict]:
    """Каждый кусок должен начинаться с начала самостоятельного предложения.

    При продолжении (и/а/но/плюс…, строчный обрывок) сначала добавляем предыдущее предложение (до 3 раз; если оно —
    конец предыдущего куска, куски просто склеиваются); если добавить нельзя — снимаем обрывок с начала (до 2 предложений
    куска); если кусок целиком из одного обрывка и ролик без него остаётся достаточно длинным — кусок убирается.
    Остаток доделает чистка (снимет ведущее «и/а/но/вот/ну»).
    """
    pieces = [dict(p) for p in pieces]
    # кусок-продолжение, чьё начало — прямое продолжение конца ДРУГОГО куска (типично: «хук» из хвоста фразы,
    # стоящей дальше), ставим сразу после этого куска: фраза снова целая, куски склеятся
    for _ in range(len(pieces)):
        moved = False
        for k, p in enumerate(pieces):
            if not _is_continuation_start(p["a"], sentences):
                continue
            j = next((j for j, q in enumerate(pieces) if j != k and q["b"] == p["a"] - 1), None)
            if j is None or j == k - 1:
                continue
            pieces.pop(k)
            pieces.insert(j + 1 if j < k else j, p)
            if pieces[-1].get("role") != "payoff":
                pieces[-1] = dict(pieces[-1], role="payoff")
            moved = True
            break
        if not moved:
            break
    pieces = _merge_adjacent(pieces)
    for k, p in enumerate(pieces):
        if not _is_continuation_start(p["a"], sentences):
            continue
        if k > 0 and pieces[k - 1]["b"] == p["a"] - 1:
            continue   # предыдущее предложение — конец предыдущего куска: они склеятся без стыка
        # 1) растём назад: до 3 предыдущих предложений, пока начало не станет самостоятельным
        start = p["a"]
        for _ in range(3):
            prev = start - 1
            used = any(q["a"] <= prev <= q["b"] for j, q in enumerate(pieces) if j != k)
            trial = dict(p, a=prev)
            if prev < 0 or used or _pieces_duration(pieces[:k] + [trial] + pieces[k + 1:], sentences) > max_total:
                break
            start = prev
            if not _is_continuation_start(start, sentences):
                break
        if start != p["a"] and not _is_continuation_start(start, sentences):
            p["a"] = start
            continue
        # 2) не вышло: снимаем обрывок с начала (до 2 предложений), если кусок длиннее одного предложения
        start = p["a"]
        for _ in range(2):
            if start >= p["b"]:
                break
            start += 1
            if not _is_continuation_start(start, sentences):
                break
        if start != p["a"] and not _is_continuation_start(start, sentences):
            p["a"] = start
    # кусок из одного непоправимого обрывка убираем, если ролик остаётся достаточно длинным
    removed = True
    while removed and len(pieces) > 1:
        removed = False
        for k, p in enumerate(pieces):
            glued = k > 0 and pieces[k - 1]["b"] == p["a"] - 1
            rest = pieces[:k] + pieces[k + 1:]
            if (p["a"] == p["b"] and not glued and _is_continuation_start(p["a"], sentences)
                    and _pieces_duration(rest, sentences) >= min_total):
                pieces = rest
                if pieces[-1].get("role") != "payoff":
                    pieces[-1] = dict(pieces[-1], role="payoff")
                removed = True
                break
    return _merge_adjacent(pieces)


def _is_service_sentence(sentence: dict) -> bool:
    text = _norm_text(sentence["text"])
    if len(text.split()) > 28:
        return False
    if SERVICE_TAIL.search(text):
        return True
    return text.rstrip().endswith("?") and bool(AUDIENCE_Q.search(text))


def _trim_service_tail(pieces: list[dict], sentences: list[dict], min_total: float) -> list[dict]:
    """Служебные предложения в конце («в чате правильно написали», «я про это пост писал», вопрос залу)
    снимаются, если ролик и без них заканчивается законченным предложением."""
    pieces = [dict(p) for p in pieces]
    for _ in range(3):
        if not pieces:
            break
        last = pieces[-1]
        if not _is_service_sentence(sentences[last["b"]]):
            break
        if last["b"] > last["a"]:
            new_last = dict(last, b=last["b"] - 1)
            candidate = pieces[:-1] + [new_last]
        elif len(pieces) > 1:
            candidate = pieces[:-1]
        else:
            break
        tail = sentences[candidate[-1]["b"]]["text"].strip()
        if not SENTENCE_END.search(tail) or _pieces_duration(candidate, sentences) < min_total:
            break
        if candidate[-1]["role"] != "payoff" and candidate[-1] is not last:
            candidate[-1] = dict(candidate[-1], role="payoff")
        pieces = candidate
    return pieces


def _apply_code_rules(d: dict, ctx: dict) -> bool:
    """Применяет правила начала куска и служебного хвоста; возвращает True, если куски изменились."""
    sentences = ctx["sentences"]
    before = [(p["a"], p["b"]) for p in d["pieces"]]
    max_total = _draft_hi(d, ctx)
    min_total = FINAL_MIN_FACTOR * ctx["min_d"] * 1.05
    pieces = _fix_piece_starts(d["pieces"], sentences, max_total, min_total)
    pieces = _fix_opening(pieces, sentences, max_total, min_total)
    pieces = _trim_service_tail(pieces, sentences, min_total)
    pieces = _fix_hook_fragment(pieces, sentences)
    pieces, _unresolved = _fix_repeats(pieces, sentences)
    hi_pre = _draft_hi(d, ctx)
    if _pieces_duration(pieces, sentences) > hi_pre:
        pieces = _trim_to_window(pieces, sentences, hi_pre, min_total) or pieces
    after = [(p["a"], p["b"]) for p in pieces]
    if after == before:
        return False
    d["pieces"] = pieces
    d.setdefault("code_rules", []).append({"before": before, "after": after})
    _refresh_seam_info(d, ctx)
    _refresh_hints(d, ctx)
    return True



def _window_gate(drafts: list[dict], ctx: dict, stage: str) -> list[dict]:
    """После любой стадии, меняющей куски: длительность речи <= итоговый максимум x PRE_TIGHTEN_SLACK.

    Сначала режем context/example (hook/payoff не трогаем); если не уложиться — ролик отсеивается с причиной.
    """
    sentences = ctx["sentences"]
    alive = []
    for d in drafts:
        hi = _draft_hi(d, ctx)
        dur = _pieces_duration(d["pieces"], sentences)
        if dur <= hi:
            alive.append(d)
            continue
        fitted = _trim_to_window(d["pieces"], sentences, hi, FINAL_MIN_FACTOR * ctx["min_d"] * 1.05)
        if not fitted and d["format"] in LONG_FORMATS and _draft_strong(d):
            # сильный длинный ролик не выбрасываем: режем на два самостоятельных
            parts = _split_long(d, ctx, stage)
            if parts:
                alive.extend(parts)
                continue
        if not fitted:
            _log_drop(ctx, d["raw"].get("title", ""), "duration",
                      f"после стадии «{stage}» речь {dur:.0f} с > {hi:.0f} с, а context/example для сокращения нет "
                      f"(hook/payoff не режем)", d.get("critic"), draft=d)
            continue
        d.setdefault("window_trims", []).append(
            {"stage": stage, "before": round(dur, 1), "after": round(_pieces_duration(fitted, sentences), 1)})
        d["pieces"] = fitted
        _refresh_seam_info(d, ctx)
        _refresh_hints(d, ctx)
        alive.append(d)
    return alive


def _refresh_seam_info(d: dict, ctx: dict) -> None:
    """Пересобирает тексты стыков по текущим кускам, сохраняя вердикты критика по номеру стыка."""
    old = {si["index"]: si for si in d.get("seams_info") or []}
    fresh = []
    for sm in _seams(d["pieces"], ctx["sentences"]):
        prev = old.get(sm["index"])
        fresh.append(dict(sm, verdict=prev["verdict"] if prev else "ok", note=prev["note"] if prev else ""))
    d["seams_info"] = fresh
    if d.get("critic"):
        d["critic"]["seams"] = [{"index": si["index"], "verdict": si["verdict"], "note": si["note"]} for si in fresh]
        d["critic"]["seams_ok"] = all(si["verdict"] == "ok" for si in fresh)


