def _topic_idx_of(d: dict, ctx: dict) -> set[int]:
    """Темы карты, к которым относится ролик: по названию темы или по пересечению предложений (>=50%)."""
    topics, id_index = ctx["topics"], ctx["id_index"]
    ids = _clip_ids(d["pieces"])
    title = _norm_text(d["raw"].get("topic", "")).strip()
    out = set()
    for ti, t in enumerate(topics):
        if title and title == _norm_text(t.get("title", "")).strip():
            out.add(ti)
            continue
        covered = set()
        for key in ("ranges", "items"):
            for a, b in _topic_ranges(t, key, id_index):
                covered |= set(range(a, b + 1))
        if ids and len(ids & covered) / len(ids) >= 0.5:
            out.add(ti)
    return out


def _needed_topics(ctx: dict) -> list[int]:
    return [ti for ti, t in enumerate(ctx["topics"])
            if int(t.get("strength", 0) or 0) >= COVERAGE_STRENGTH or t.get("kind") == "list"]


def _draft_duration(d: dict, ctx: dict) -> float:
    return _pieces_duration(d["pieces"], ctx["sentences"])


def _chief_block(n: int, d: dict, ctx: dict) -> str:
    critic = d.get("critic") or {}
    scores = ", ".join(f"{k} {critic[k]}" for k in ALL_SCORES if k in critic and not critic.get("unavailable"))
    flags = []
    if d.get("resurrected"):
        flags.append("ВОССТАНОВЛЕН для покрытия темы: " + d["resurrected"])
    if critic.get("repaired"):
        flags.append("прошёл ремонт (раунд 3)")
    if _near_miss(critic, d):
        flags.append("остались замечания")
    parts = [f"=== КАНДИДАТ {n}: {d['raw'].get('title', '')} ===",
             f"ТЕМА: {d['raw'].get('topic', '')} | ФОРМАТ: {d['format']} | ~{_draft_duration(d, ctx):.0f} с",
             f"ТЕЗИС: {d['thesis']}"]
    if scores:
        parts.append(f"ОЦЕНКИ КРИТИКА: {scores}")
    if flags:
        parts.append("ПОМЕТКИ: " + "; ".join(flags))
    problems = [str(x) for x in (critic.get("problems") or [])][:4]
    if problems:
        parts.append("ЗАМЕЧАНИЯ: " + " | ".join(problems))
    parts += ["ТЕКСТ:", _clip_text(d["pieces"], ctx["sentences"], with_ids=True)]
    return "\n".join(parts)


def _chief_topics_text(ctx: dict, pool: list[dict]) -> str:
    cover: dict[int, list[int]] = {}
    for n, d in enumerate(pool, 1):
        for ti in _topic_idx_of(d, ctx):
            cover.setdefault(ti, []).append(n)
    needed = set(_needed_topics(ctx))
    lines = []
    for ti, t in enumerate(ctx["topics"][:60]):
        mark = " [ОБЯЗАТЕЛЬНА К ПОКРЫТИЮ]" if ti in needed else ""
        have = ("покрыта кандидатами: " + ", ".join(map(str, cover[ti]))) if ti in cover else "кандидатов нет"
        lines.append(f"- [{t.get('kind', 'thesis')}] {t.get('title')} (сила {t.get('strength')}){mark}: "
                     f"{t.get('thesis')} | {have}")
    return "\n".join(lines) or "(тем нет)"


def _rank_fallback(drafts: list[dict]) -> list[dict]:
    return sorted(drafts, key=lambda d: (bool((d.get("critic") or {}).get("hook_warning")),
                                         -sum(_scores_of(d.get("critic")).values()),
                                         -int(d["raw"].get("score", 0) or 0)))


def _unreject(ctx: dict, d: dict) -> None:
    ctx["rejected"] = [r for r in ctx.get("rejected", []) if r is not d]
    d.pop("reject", None)


def _chief_editor(drafts: list[dict], ctx: dict) -> list[dict]:
    """Один запрос главного редактора по ВСЕМ кандидатам: publish | repair_more | drop, ранг, покрытие, дубли, названия."""
    options = ctx["options"] or {}
    if not drafts:
        return []
    if not options.get("chief_editor", True):
        return _rank_fallback(drafts)
    pool = list(drafts)
    # покрытие: для сильной/list-темы без кандидата берём лучший отсеянный по критику черновик
    needed = _needed_topics(ctx)
    covered = {ti for d in pool for ti in _topic_idx_of(d, ctx)}
    for ti in needed:
        if ti in covered:
            continue
        cands = [r for r in ctx.get("rejected", []) if str(r.get("reject", {}).get("stage", "")).startswith(("critic", "repair"))
                 and ti in _topic_idx_of(r, ctx) and r not in pool]
        if cands:
            best = max(cands, key=lambda r: sum(_scores_of(r.get("critic")).values()))
            best["resurrected"] = (f"тема «{ctx['topics'][ti].get('title')}» иначе не представлена; "
                                   f"отсеян: {best['reject']['reason'][:140]}")
            pool.append(best)
            covered |= _topic_idx_of(best, ctx)
    prompt = _chief_prompt(_chief_topics_text(ctx, pool),
                           "\n\n".join(_chief_block(n, d, ctx) for n, d in enumerate(pool, 1)),
                           audience=ctx.get("audience", ""), min_d=ctx["min_d"], max_d=ctx["max_d"])
    try:
        data = _call(ctx["llm"], ctx["provider"], prompt, CHIEF_SCHEMA, ctx["work_dir"], "chief_editor")
    except Exception as exc:
        ctx["chief_error"] = str(exc)
        for d in pool:
            if d.get("resurrected"):
                d.pop("resurrected", None)
        return _rank_fallback(drafts)
    _write_json(ctx["work_dir"] / "editorial_chief_raw.json", data)
    by_clip = {}
    for x in data.get("decisions") or []:
        try:
            by_clip[int(x.get("clip"))] = x
        except (TypeError, ValueError):
            continue
    decided: list[tuple[dict, str, dict]] = []
    for n, d in enumerate(pool, 1):
        x = by_clip.get(n)
        if x is None:
            decision, info = ("drop" if d.get("resurrected") else "publish"), {"reason": "главный редактор не вернул решение"}
            x = {"rank": 500 + n}
        else:
            decision = x.get("decision") if x.get("decision") in {"publish", "repair_more", "drop"} else "publish"
            info = x
        trims = _register_trims(x.get("trims"), d, ctx, "chief")
        if trims and decision == "drop" and not int(x.get("duplicate_of") or 0):
            # локальный дефект (обрывок, паразитная фраза) подрезается вырезом, а ролик не выбрасывается
            decision = "publish"
            d["chief_local_fix"] = [{"sentence": t["sentence"], "text": t["text"]} for t in trims]
        elif trims:
            d["chief_local_fix"] = [{"sentence": t["sentence"], "text": t["text"]} for t in trims]
        if x.get("spinoffs") and decision != "drop":
            d["spinoffs_raw"] = list(x.get("spinoffs") or [])
        decided.append((d, decision, x))
    # покрытие: сильная/list-тема не может остаться без ролика, если кандидат есть
    keep = {id(d) for d, dec, _ in decided if dec != "drop"}
    for ti in needed:
        members = [(d, dec, x) for d, dec, x in decided if ti in _topic_idx_of(d, ctx)]
        if not members or any(id(d) in keep for d, _, _ in members):
            continue
        d, dec, x = max(members, key=lambda m: (not m[0].get("resurrected"), sum(_scores_of(m[0].get("critic")).values())))
        keep.add(id(d))
        d["coverage_override"] = f"тема «{ctx['topics'][ti].get('title')}» (сила {ctx['topics'][ti].get('strength')}) осталась бы без ролика"
        for i, (dd, _, xx) in enumerate(decided):
            if dd is d:
                decided[i] = (dd, "repair_more" if dec == "drop" and dd.get("critic") and _near_miss(dd["critic"], dd) else "publish", xx)
    # дубли: пересечение предложений > 50% меньшего ролика — оставляем лучший по рангу главреда
    final: list[tuple[dict, str, dict]] = []
    for item in sorted([m for m in decided if id(m[0]) in keep], key=lambda m: int(m[2].get("rank", 999) or 999)):
        ids = _clip_ids(item[0]["pieces"])
        dup = next((k for k in final if ids and len(ids & _clip_ids(k[0]["pieces"])) / max(1, min(len(ids), len(_clip_ids(k[0]["pieces"])))) > 0.5), None)
        if dup is not None:
            _log_drop(ctx, item[0]["raw"].get("title", ""), "chief_editor",
                      "дубль: пересекается с более высоким роликом «" + dup[0]["raw"].get("title", "") + "»",
                      item[0].get("critic"), draft=item[0])
            continue
        final.append(item)
    kept_ids = {id(d) for d, _, _ in final}
    for d, dec, x in decided:
        if id(d) in kept_ids:
            if d.get("reject"):
                _unreject(ctx, d)
            continue
        if d.get("reject"):   # уже в rejected после критика/ремонта
            continue
        if id(d) in keep:
            continue
        _log_drop(ctx, d["raw"].get("title", ""), "chief_editor",
                  "главред: " + str(x.get("reason", "")).strip() if x.get("reason") else "главред: не публикуем",
                  d.get("critic"), draft=d)
    # repair_more: ещё один раунд ремонта
    more = [d for d, dec, _ in final if dec == "repair_more"]
    extras = {id(d): ["замечание главного редактора: " + str(x.get("reason", ""))]
              for d, dec, x in final if dec == "repair_more"}
    survivors = {id(d) for d in _repair_round(more, ctx, "repair_chief", extras)} if more else set()
    result = []
    for d, dec, x in final:
        if dec == "repair_more" and id(d) not in survivors:
            continue
        rank = len(result) + 1
        old_title = d["raw"].get("title", "")
        new_title = str(x.get("title", "")).strip()
        title_fixed = bool(new_title) and _norm_text(new_title).strip() != _norm_text(old_title).strip()
        if title_fixed:
            d["raw"] = dict(d["raw"], title=new_title)
            ctx.setdefault("topic_by_title", {})[new_title] = ctx.get("topic_by_title", {}).get(old_title, "")
        d["chief"] = {"decision": dec, "reason": str(x.get("reason", "")).strip(), "rank": rank,
                      "title_fixed": title_fixed, "original_title": old_title if title_fixed else "",
                      "duplicate_of": x.get("duplicate_of") or 0}
        if d.get("coverage_override"):
            d["chief"]["coverage_override"] = d["coverage_override"]
        if d.get("resurrected"):
            d["chief"]["resurrected"] = d["resurrected"]
        if d.get("chief_local_fix"):
            d["chief"]["local_fix"] = d["chief_local_fix"]
        result.append(d)
        for raw_spin in d.pop("spinoffs_raw", []) or []:
            spin = _make_spinoff(d, raw_spin, ctx)
            if spin is not None:
                result.append(spin)
    return result


def _tighten(drafts, sentences, words, llm, provider, work_dir, options) -> list[list[tuple[int, int, str]]]:
    """Возвращает для каждого ролика список (w0, w1, reason) по глобальным индексам слов."""
    if not drafts:
        return []
    result: list[list[tuple[int, int, str]]] = [[] for _ in drafts]
    if not options.get("tighten", True):  # чистка отключена пользователем: куски остаются как сказаны
        return result
    if not words or any(sentences[p["a"]]["w0"] < 0 for d in drafts for p in d["pieces"]):
        return result
    regexes = _filler_regexes(options)
    ranges_per_clip = [_words_of_pieces(d["pieces"], sentences) for d in drafts]

    llm_cuts: dict[int, list[dict]] = {}   # ключ — глобальный номер ролика (с 1)
    if options.get("llm_tighten", True):
        def tighten_batch(arg):
            batch_no, start = arg
            chunk = list(range(start, min(len(drafts), start + CRITIC_BATCH)))
            blocks = []
            for local, g in enumerate(chunk, 1):
                parts = [" ".join(f"#{i} {words[i].get('text', '')}" for i in range(w0, w1 + 1))
                         for w0, w1 in ranges_per_clip[g]]
                blocks.append(f"=== РОЛИК {local}: {drafts[g]['raw'].get('title', '')} ===\n" + "\n---\n".join(parts))
            task = "tighten" if batch_no == 1 else f"tighten_b{batch_no}"
            try:
                data = _call(llm, provider, _tighten_prompt("\n\n".join(blocks)), TIGHTEN_SCHEMA, work_dir, task)
            except Exception:
                return {}
            _write_json(work_dir / ("editorial_tighten_raw.json" if batch_no == 1 else f"editorial_tighten_raw_b{batch_no}.json"), data)
            found = {}
            for c in data.get("clips") or []:
                try:
                    local = int(c.get("clip"))
                except (TypeError, ValueError):
                    continue
                if 1 <= local <= len(chunk):
                    found[chunk[local - 1] + 1] = list(c.get("cuts") or [])
            return found

        starts = list(enumerate(range(0, len(drafts), CRITIC_BATCH), 1))
        for found in _run_batches(tighten_batch, starts, int(options.get("parallel", 1) or 1)):
            llm_cuts.update(found)

    for n, wr in enumerate(ranges_per_clip, 1):
        total_words = sum(b - a + 1 for a, b in wr)
        chosen: dict[int, str] = {}
        # детерминированный минимум
        for a, b in wr:
            for i in _auto_filler_indices(range(a, b + 1), words, regexes):
                chosen[i] = "filler"
        budget = int(total_words * 0.25)
        for c in llm_cuts.get(n, []):
            try:
                w0, w1 = int(c["w0"]), int(c["w1"])
            except (KeyError, TypeError, ValueError):
                continue
            if w0 > w1:
                w0, w1 = w1, w0
            reason = c.get("reason") if c.get("reason") in CUT_REASONS else "filler"
            if not any(a <= w0 and w1 <= b for a, b in wr):
                continue
            span = [i for i in range(w0, w1 + 1) if i not in chosen]
            if len(chosen) + len(span) > budget and reason != "filler":
                continue
            for i in span:
                chosen[i] = reason
        draft = drafts[n - 1]
        # порядковые слова перечня должны идти 1, 2, 3: конфликтующие удаляем (только слово)
        if draft.get("format") == "list":
            for idx in _ordinal_conflicts(_clip_ordinals(draft["pieces"], sentences, words)):
                chosen[idx] = "ordinal"
        # вводная разминка («ну, вот, смотрите…») не должна открывать ролик; ведущее «и/а/но/плюс/то есть» открывать
        # любой кусок тоже не должно (если продолжение не удалось закрыть предыдущим предложением)
        for pi, piece in enumerate(draft["pieces"]):
            first = sentences[piece["a"]]
            i, removed_lead = first["w0"], 0
            drop_set = LEADING_HEDGES | CONTINUATION_WORDS if pi == 0 else CONTINUATION_WORDS | {"вот", "ну"}
            while i <= first["w1"] - 3 and removed_lead < 3:
                tok = _norm_token(words[i].get("text", ""))
                nxt = _norm_token(words[i + 1].get("text", "")) if i + 1 <= first["w1"] else ""
                if tok == "то" and nxt == "есть" and i + 1 <= first["w1"] - 3:
                    chosen[i] = chosen[i + 1] = "false_start"
                    i += 2
                    removed_lead += 2
                elif tok in drop_set:
                    chosen[i] = "filler" if tok in LEADING_HEDGES else "false_start"
                    i += 1
                    removed_lead += 1
                else:
                    break
        # рваность: не больше 2 вырезов на предложение, фрагменты >= 0.6 с, без одинаковых слов встык
        sent_ranges = [(sentences[i]["w0"], sentences[i]["w1"]) for p in draft["pieces"]
                       for i in range(p["a"], p["b"] + 1)]
        _limit_choppiness(chosen, words, sent_ranges)
        _splice_budget(chosen, words, wr)
        _limit_cut_density(chosen, words, sent_ranges)
        # локальные дефекты, найденные критиком/ремонтом/главредом/отсмотром, вырезаются всегда (не больше 25% слов)
        forced_budget = int(total_words * 0.25)
        forced_used = 0
        for fc in draft.get("forced_cuts") or []:
            f0, f1 = int(fc["w0"]), int(fc["w1"])
            if not any(a <= f0 and f1 <= b for a, b in wr) or forced_used + (f1 - f0 + 1) > forced_budget:
                continue
            for i in range(f0, f1 + 1):
                chosen[i] = FORCED_REASON
            forced_used += f1 - f0 + 1
        # нельзя вырезать слово целого куска
        for a, b in wr:
            if all(i in chosen for i in range(a, b + 1)):
                for i in range(a, b + 1):
                    chosen.pop(i, None)
        result[n - 1] = _group(chosen)
    return result



def _is_pure_filler(i: int, chosen: dict[int, str], words: list[dict]) -> bool:
    return chosen.get(i) == "filler"


def _cut_groups(chosen: dict[int, str], w0: int, w1: int) -> list[list[int]]:
    """Непрерывные группы вырезаемых слов [first, last] внутри предложения w0..w1."""
    groups: list[list[int]] = []
    for i in range(w0, w1 + 1):
        if i not in chosen:
            continue
        if groups and groups[-1][1] == i - 1:
            groups[-1][1] = i
        else:
            groups.append([i, i])
    return groups


def _limit_choppiness(chosen: dict[int, str], words: list[dict], sentence_ranges: list[tuple[int, int]]) -> None:
    """Правила рваности (меняет chosen на месте), для каждого предложения:
    1) вырез не должен сводить одинаковое слово встык («это [вот] это» -> «это это»): такой вырез отменяется;
    2) не больше MAX_CUTS_PER_SENTENCE вырезов (одиночные слова-паразиты не считаются): остаются самые длинные;
    3) оставшийся между вырезами кусок короче MIN_KEPT_FRAGMENT с склеивается обратно (отменяется меньший из соседних вырезов).
    """
    def uncut(group):
        for i in range(group[0], group[1] + 1):
            chosen.pop(i, None)

    for w0, w1 in sentence_ranges:
        for group in _cut_groups(chosen, w0, w1):
            left, right = group[0] - 1, group[1] + 1
            if left >= w0 and right <= w1 and left not in chosen and right not in chosen:
                a, b = _norm_token(words[left].get("text", "")), _norm_token(words[right].get("text", ""))
                if a and a == b:
                    uncut(group)
        groups = _cut_groups(chosen, w0, w1)
        countable = [g for g in groups if not (g[0] == g[1] and _is_pure_filler(g[0], chosen, words))]
        if len(countable) > MAX_CUTS_PER_SENTENCE:
            keep = sorted(countable, key=lambda g: (g[1] - g[0], -g[0]), reverse=True)[:MAX_CUTS_PER_SENTENCE]
            for g in countable:
                if g not in keep:
                    uncut(g)
        for _ in range(10):
            groups = _cut_groups(chosen, w0, w1)
            bad = None
            for g, h in zip(groups, groups[1:]):
                first, last = g[1] + 1, h[0] - 1
                if first <= last and float(words[last]["end"]) - float(words[first]["start"]) < MIN_KEPT_FRAGMENT:
                    bad = (g, h)
                    break
            if bad is None:
                break
            g, h = bad
            uncut(g if (g[1] - g[0], g[0]) <= (h[1] - h[0], h[0]) else h)


EH_TOKEN = re.compile(r"^(?:э+|м+|а+|ы+|гм+|хм+|эм+)(?:-(?:э+|м+|а+|ы+|гм+|хм+|эм+))*$")
HEDGE_TOKENS_CUT = {"ну", "вот", "типа", "значит", "короче", "собственно", "как", "бы", "так", "скажем", "блин",
                    "вообще", "кстати"}


def _token_kind(token: str) -> str:
    if EH_TOKEN.match(token):
        return "eh"
    return "hedge" if token in HEDGE_TOKENS_CUT else "content"


def _group_value(g: list[int], chosen: dict[int, str], words: list[dict]) -> tuple:
    """Чем больше, тем ценнее вырез: порядковые > содержательные (повтор/оговорка/реплика в сторону) > паразиты."""
    reasons = {chosen.get(i) for i in range(g[0], g[1] + 1)}
    dur = float(words[g[1]]["end"]) - float(words[g[0]]["start"])
    if "ordinal" in reasons:
        return (3, dur)
    if reasons - {"filler"}:
        return (2, dur)
    return (1, dur)


def _splice_budget(chosen: dict[int, str], words: list[dict], piece_ranges: list[tuple[int, int]]) -> None:
    """Бюджет склеек (меняет chosen на месте). Склейка = вырез внутри куска, стык кусков или пауза >= 0.9 с.

    1) «э-э/эм/ммм» и «ну/вот/как бы/типа» вырезаются только между паузами >= CLEAN_PAUSE (чистая точка реза);
       оговорка/повтор — только если вырезаемый кусок >= MIN_REPEAT_SPAN;
    2) два выреза ближе MIN_SPLICE_GAP (и вырез рядом со стыком кусков): если между ними одни паразиты — сливаем в один
       вырез, иначе отменяем менее ценный (паразиты остаются);
    3) в среднем не больше одной склейки на SPLICE_EVERY секунд ролика: лишние (наименее ценные) отменяются.
    Порядковые слова перечня (ordinal) не трогаются.
    """
    def uncut(g):
        for i in range(g[0], g[1] + 1):
            chosen.pop(i, None)

    def start(i):
        return float(words[i]["start"])

    def end(i):
        return float(words[i]["end"])

    def inner_groups():
        out = []
        for k, (a, b) in enumerate(piece_ranges):
            for g in _cut_groups(chosen, a, b):
                if g[0] > a and g[1] < b:
                    out.append((k, a, b, g))
        return out

    # 1) тип выреза и чистая точка реза
    for k, a, b, g in inner_groups():
        reasons = {chosen.get(i) for i in range(g[0], g[1] + 1)}
        if "ordinal" in reasons:
            continue
        if reasons == {"filler"} or not reasons - {"filler"}:
            if min(start(g[0]) - end(g[0] - 1), start(g[1] + 1) - end(g[1])) < CLEAN_PAUSE:
                uncut(g)
        elif end(g[1]) - start(g[0]) < MIN_REPEAT_SPAN:
            uncut(g)

    # 2) близкие склейки
    for _ in range(100):
        changed = False
        for k, a, b, g in inner_groups():
            if chosen.get(g[0]) == "ordinal":
                continue
            seam_left = k > 0 and end(g[0] - 1) - start(a) < MIN_SPLICE_GAP
            seam_right = k < len(piece_ranges) - 1 and end(b) - start(g[1] + 1) < MIN_SPLICE_GAP
            if seam_left or seam_right:
                uncut(g)
                changed = True
                break
        if changed:
            continue
        for k, a, b in [(k, a, b) for k, (a, b) in enumerate(piece_ranges)]:
            groups = [g for g in _cut_groups(chosen, a, b) if g[0] > a and g[1] < b]
            for g, h in zip(groups, groups[1:]):
                between = range(g[1] + 1, h[0])
                if end(h[0] - 1) - start(g[1] + 1) >= MIN_SPLICE_GAP:
                    continue
                if all(_token_kind(_norm_token(words[i].get("text", ""))) != "content" for i in between):
                    for i in between:
                        chosen[i] = "filler"
                else:
                    uncut(min((g, h), key=lambda x: _group_value(x, chosen, words)))
                changed = True
                break
            if changed:
                break
        if not changed:
            break

    # 3) общий бюджет
    def duration():
        total = sum(end(b) - start(a) for a, b in piece_ranges)
        return total - sum(end(i) - start(i) for i in chosen if any(a <= i <= b for a, b in piece_ranges))

    pauses = sum(1 for a, b in piece_ranges for i in range(a, b)
                 if i not in chosen and i + 1 not in chosen and start(i + 1) - end(i) >= 0.9)
    budget = int(duration() // SPLICE_EVERY) - (len(piece_ranges) - 1) - pauses
    groups = [x[3] for x in inner_groups() if chosen.get(x[3][0]) != "ordinal"]
    while len(groups) > max(0, budget):
        victim = min(groups, key=lambda g: _group_value(g, chosen, words))
        uncut(victim)
        groups.remove(victim)


def _limit_cut_density(chosen: dict[int, str], words: list[dict], sentence_ranges: list[tuple[int, int]],
                       window: float = CUT_DENSITY_WINDOW, max_groups: int = MAX_CUTS_IN_WINDOW) -> None:
    """В любом окне `window` секунд не больше `max_groups` вырезов: лишние отменяются (сначала одиночные
    слова-паразиты, потом самые короткие), чтобы речь не рассыпалась на стыки."""
    for _ in range(200):
        groups = []
        for w0, w1 in sentence_ranges:
            groups += _cut_groups(chosen, w0, w1)
        groups.sort(key=lambda g: float(words[g[0]]["start"]))
        over = None
        for i in range(len(groups)):
            t0 = float(words[groups[i][0]]["start"])
            inside = [g for g in groups[i:] if float(words[g[0]]["start"]) - t0 <= window]
            if len(inside) > max_groups:
                over = inside
                break
        if over is None:
            return
        victim = min(over, key=lambda g: (not (g[0] == g[1] and chosen.get(g[0]) == "filler"), g[1] - g[0], -g[0]))
        for i in range(victim[0], victim[1] + 1):
            chosen.pop(i, None)


def _group(chosen: dict[int, str]) -> list[tuple[int, int, str]]:
    out: list[list] = []
    for i in sorted(chosen):
        if out and out[-1][1] + 1 == i and out[-1][2] == chosen[i]:
            out[-1][1] = i
        else:
            out.append([i, i, chosen[i]])
    return [(a, b, r) for a, b, r in out]


def _to_candidate(draft: dict, sentences: list[dict], words: list[dict], cuts_idx) -> dict:
    raw = draft["raw"]
    segments = []
    for p in draft["pieces"]:
        sa, sb = sentences[p["a"]], sentences[p["b"]]
        if sa["w0"] >= 0 and words:
            start, end = float(words[sa["w0"]]["start"]), float(words[sb["w1"]]["end"])
        else:
            start, end = float(sa["start"]), float(sb["end"])
        segments.append({"start": start, "end": end, "role": p["role"],
                         "sentence_from": sa["id"], "sentence_to": sb["id"]})
    cuts = []
    for w0, w1, reason in cuts_idx:
        cuts.append({"start": float(words[w0]["start"]), "end": float(words[w1]["end"]), "reason": reason})
    cand = {
        "title": str(raw.get("title", "")).strip(),
        "thesis": draft.get("thesis") or str(raw.get("thesis", "")).strip(),
        "topic": str(raw.get("topic", "")).strip(),
        "format": draft.get("format", "thesis"),
        "seams": [{"index": si["index"], "from_sentence": si["from_sentence"], "to_sentence": si["to_sentence"],
                   "from_text": si["from_text"], "to_text": si["to_text"], "where": si["where"],
                   "verdict": si["verdict"], "note": si["note"]} for si in draft.get("seams_info", [])],
        "description": str(raw.get("description", "")).strip(),
        "hook": clean_hook_text(raw.get("hook_text"), raw.get("title", "")),
        "hook_text": clean_hook_text(raw.get("hook_text"), raw.get("title", "")),
        "score": int(raw.get("score", 0) or 0),
        "rationale": str(raw.get("rationale", "")).strip(),
        "critic": draft.get("critic") or {},
        "segments": segments,
        "cuts": cuts,
    }
    if draft.get("chief"):
        cand["chief_editor"] = dict(draft["chief"])
    if draft.get("repair"):
        cand["repair"] = dict(draft["repair"])
    for key in ("spinoff_of", "split_of", "source"):
        if draft.get(key):
            cand[key] = draft[key]
    if raw.get("moment"):
        cand["moment"] = str(raw["moment"])
    if draft.get("forced_cuts"):
        cand["local_fixes"] = [{"sentence": c["sentence"], "text": c["text"], "source": c.get("source", "")}
                               for c in draft["forced_cuts"]]
    if draft.get("code_rules"):
        cand["code_rules"] = list(draft["code_rules"])
    cand["start"] = min(s["start"] for s in segments)
    cand["end"] = max(s["end"] for s in segments)
    intervals = assembly.keep_intervals(cand, words)
    cand["duration"] = assembly.assembled_duration(intervals)
    return cand
