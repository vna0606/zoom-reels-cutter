def _normalize_pieces(raw_pieces, id_index: dict[str, int]) -> list[dict]:
    """Валидирует куски: неизвестные id -> отброс, from>to -> swap, пересечения -> убрать."""
    pieces: list[dict] = []
    covered: set[int] = set()
    for raw in raw_pieces or []:
        if not isinstance(raw, dict):
            continue
        a, b = id_index.get(str(raw.get("from", "")).strip().upper()), id_index.get(str(raw.get("to", "")).strip().upper())
        if a is None and b is None:
            continue
        if a is None:
            a = b
        if b is None:
            b = a
        if a > b:
            a, b = b, a
        role = str(raw.get("role", "point")).strip().lower()
        if role not in ROLES:
            role = "point"
        fresh = [i for i in range(a, b + 1) if i not in covered]
        if not fresh:
            continue
        # непрерывные подотрезки
        run_start = fresh[0]
        prev = fresh[0]
        runs = []
        for i in fresh[1:]:
            if i != prev + 1:
                runs.append((run_start, prev))
                run_start = i
            prev = i
        runs.append((run_start, prev))
        for ra, rb in runs:
            pieces.append({"a": ra, "b": rb, "role": role})
            covered.update(range(ra, rb + 1))
    return _natural_order(pieces)


def _natural_order(pieces: list[dict]) -> list[dict]:
    """Естественный порядок: куски идут в хронологическом порядке записи (никаких тизеров, вынесенных вперёд).

    Сортирует по положению в записи, склеивает соседние, роли приводит в соответствие: «hook» только у первого
    куска, «payoff» только у последнего (чужой payoff в середине становится point).
    """
    ordered = sorted((dict(p) for p in pieces), key=lambda p: (p["a"], p["b"]))
    merged: list[dict] = []
    for p in ordered:
        if merged and p["a"] <= merged[-1]["b"] + 1:
            merged[-1]["b"] = max(merged[-1]["b"], p["b"])
            if p.get("role") == "payoff":
                merged[-1]["role"] = "payoff"
        else:
            merged.append(p)
    for k, p in enumerate(merged):
        if k > 0 and p.get("role") == "hook":
            p["role"] = "context"
        if k < len(merged) - 1 and p.get("role") == "payoff":
            p["role"] = "point"
    return merged


def is_chronological(pieces: list[dict]) -> bool:
    """Куски (a/b) идут строго по возрастанию позиции в записи."""
    return all(q["a"] > p["b"] for p, q in zip(pieces, pieces[1:]))


def segments_chronological(segments: list[dict]) -> bool:
    """Сегменты кандидата (start/end) идут в хронологическом порядке записи."""
    return all(float(q["start"]) >= float(p["end"]) - 1e-6 for p, q in zip(segments, segments[1:]))


def _raw_in_order(raw_pieces, id_index: dict[str, int]) -> bool:
    """Ответ ИИ перечисляет куски в хронологическом порядке (иначе это перестановка/тизер)."""
    last = -1
    for raw in raw_pieces or []:
        if not isinstance(raw, dict):
            continue
        a = id_index.get(str(raw.get("from", "")).strip().upper())
        b = id_index.get(str(raw.get("to", "")).strip().upper())
        a = a if a is not None else b
        if a is None:
            continue
        if a < last:
            return False
        last = max(last, a, b if b is not None else a)
    return True


def clean_hook_text(text, fallback: str = "") -> str:
    """hook_text: короткий (не больше HOOK_TEXT_MAX_WORDS слов) заголовок-хук для визуала; не озвучивается."""
    value = " ".join(str(text or "").replace("\n", " ").split()).strip(" \"'«»“”")
    if not value:
        value = " ".join(str(fallback or "").split()).strip(" \"'«»“”")
    words = value.split()
    if len(words) > HOOK_TEXT_MAX_WORDS:
        value = " ".join(words[:HOOK_TEXT_MAX_WORDS]).rstrip(" ,;:—-")
    return value


def _piece_duration(piece: dict, sentences: list[dict]) -> float:
    return sum(sentences[i]["end"] - sentences[i]["start"] for i in range(piece["a"], piece["b"] + 1))


def _pieces_duration(pieces: list[dict], sentences: list[dict]) -> float:
    return sum(_piece_duration(p, sentences) for p in pieces)


def _trim_to_fit(pieces: list[dict], sentences: list[dict], max_d: float) -> list[dict]:
    """Убирает context-куски (не первый и не последний), пока ролик не уложится в max_d."""
    pieces = list(pieces)
    while _pieces_duration(pieces, sentences) > max_d:
        victims = [i for i, p in enumerate(pieces) if p["role"] == "context" and 0 < i < len(pieces) - 1]
        if not victims:
            victims = [i for i, p in enumerate(pieces) if p["role"] == "context" and len(pieces) > 2]
        if not victims:
            break
        victim = max(victims, key=lambda i: _piece_duration(pieces[i], sentences))
        del pieces[victim]
    return pieces


TRIM_ROLES = ("context", "example")   # hook и payoff не трогаем никогда


def _trim_to_window(pieces: list[dict], sentences: list[dict], max_total: float,
                    min_total: float = 0.0) -> list[dict] | None:
    """Укладывает куски в max_total: сначала context, потом example; hook/payoff/point не трогаются.

    Целый кусок убирается, если остаток не короче min_total; иначе кусок укорачивается по предложениям
    (context — с начала, example — с конца), но не меньше одного предложения. None — уложиться нельзя.
    """
    pieces = [dict(p) for p in pieces]
    if _pieces_duration(pieces, sentences) <= max_total:
        return pieces
    for role in TRIM_ROLES:
        while _pieces_duration(pieces, sentences) > max_total:
            idxs = [i for i, p in enumerate(pieces) if p.get("role") == role]
            if not idxs or len(pieces) <= 1:
                break
            i = max(idxs, key=lambda k: _piece_duration(pieces[k], sentences))
            rest = pieces[:i] + pieces[i + 1:]
            if _pieces_duration(rest, sentences) >= min_total or _piece_duration(pieces[i], sentences) <= 0:
                pieces = rest
                continue
            p = pieces[i]
            while p["a"] < p["b"] and _pieces_duration(pieces, sentences) > max_total:
                if role == "context":
                    p["a"] += 1
                else:
                    p["b"] -= 1
            if _pieces_duration(pieces, sentences) > max_total:
                pieces = rest    # даже один кусок-предложение мешает: убираем целиком
    if not pieces or _pieces_duration(pieces, sentences) > max_total:
        return None
    return pieces


def _words_of_pieces(pieces: list[dict], sentences: list[dict]) -> list[tuple[int, int]]:
    return [(sentences[p["a"]]["w0"], sentences[p["b"]]["w1"]) for p in pieces]


def _clip_text(pieces: list[dict], sentences: list[dict], with_ids: bool = True) -> str:
    lines = []
    for p in pieces:
        for i in range(p["a"], p["b"] + 1):
            s = sentences[i]
            lines.append(f"{s['id']} {s['text']}" if with_ids else s["text"])
    return "\n".join(lines)


def _filler_regexes(options: dict):
    patterns = options.get("filler_patterns")
    if patterns is None:
        patterns = DEFAULT_FILLER_PATTERNS
    return [re.compile(r"^(?:%s)$" % p, re.IGNORECASE) for p in patterns]


def _norm_token(text: str) -> str:
    return re.sub(r"^[^0-9A-Za-zА-Яа-яЁё]+|[^0-9A-Za-zА-Яа-яЁё]+$", "", str(text).strip()).lower().replace("ё", "е")


def _auto_filler_indices(widx: range, words: list[dict], regexes) -> list[int]:
    out = []
    for i in widx:
        tok = _norm_token(words[i].get("text", ""))
        if tok and any(r.match(tok) for r in regexes):
            out.append(i)
    return out


