def _window_ids(pieces: list[dict], n_sentences: int, radius: int = WINDOW_RADIUS) -> set[int]:
    out: set[int] = set()
    for p in pieces:
        out |= set(range(max(0, p["a"] - radius), min(n_sentences, p["b"] + radius + 1)))
    return out - _clip_ids(pieces)


def _critique_block(n: int, d: dict, ctx: dict, round_no: int) -> str:
    sentences = ctx["sentences"]
    parts = [f"=== РОЛИК {n}: {d['raw'].get('title', '')} ===",
             f"ФОРМАТ: {d['format']}", f"ТЕЗИС: {d['thesis'] or d['raw'].get('description', '')}"]
    parts += [f"ЗАМЕЧАНИЕ ПРОВЕРКИ: {h}" for h in d.get("problems_hint") or []]
    parts += ["ТЕКСТ РОЛИКА (в порядке воспроизведения):", _clip_text(d["pieces"], sentences)]
    seams = _seams(d["pieces"], sentences)
    if seams:
        parts.append("СТЫКИ:")
        for sm in seams:
            parts.append(f"Стык {sm['index']}: …{sm['from_text'][-180:]} ⟶ {sm['to_text'][:180]}… ({sm['where']})")
    else:
        parts.append("СТЫКИ: нет (один непрерывный отрезок записи)")
    window = sorted(_window_ids(d["pieces"], len(sentences)))
    if window:
        parts.append("ДОСТУПНЫЕ ПРЕДЛОЖЕНИЯ ВОКРУГ (в ролике их нет; можно добавить в pieces):")
        parts += [f"{sentences[i]['id']} {sentences[i]['text']}" for i in window]
    if round_no > 1 and d.get("round1_problems"):
        parts.append("ПРОБЛЕМЫ РАУНДА 1 (проверь, что исправлены):")
        parts += [f"- {x}" for x in d["round1_problems"]]
    return "\n".join(parts)


def _restrict_pieces(raw_pieces, allowed: set[int], sentences, id_index) -> list[dict]:
    """Оставляет в кусках только разрешённые предложения (куски режутся по границам разрешённых)."""
    cleaned = []
    for p in _normalize_pieces(raw_pieces, id_index):
        run = []
        for i in range(p["a"], p["b"] + 1):
            if i in allowed:
                run.append(i)
            elif run:
                cleaned.append({"from": sentences[run[0]]["id"], "to": sentences[run[-1]]["id"], "role": p["role"]})
                run = []
        if run:
            cleaned.append({"from": sentences[run[0]]["id"], "to": sentences[run[-1]]["id"], "role": p["role"]})
    return _normalize_pieces(cleaned, id_index)


def _apply_fix(v: dict, d: dict, ctx: dict, allow_reorder: bool = True) -> list[dict] | None:
    """Правка ИИ -> куски. Порядок всегда естественный (хронологический). allow_reorder=False (ремонт, главред):
    ответ, где куски перечислены не по порядку записи, — это перестановка/тизер, правка отклоняется."""
    sentences = ctx["sentences"]
    if not allow_reorder and not _raw_in_order(v.get("pieces"), ctx["id_index"]):
        return None
    allowed = _clip_ids(d["pieces"]) | _window_ids(d["pieces"], len(sentences))
    fixed = _restrict_pieces(v.get("pieces"), allowed, sentences, ctx["id_index"])
    if not fixed:
        return None
    fmt = d["format"]
    strong = _draft_strong(d)
    fixed = _fit_duration(fixed, sentences, _max_for(fmt, ctx["max_d"], strong), _hi_limit(fmt, ctx["max_d"], strong),
                          ctx["lo_limit"])
    if not fixed or _count_regions(fixed, sentences) > MAX_REGIONS:
        return None
    return fixed


def _locate_phrase(sentence: dict, words: list[dict], text: str) -> tuple[int, int] | None:
    """Индексы слов (w0, w1) дословной фразы внутри предложения; допускается отличие в одно слово."""
    import difflib
    if sentence["w0"] < 0 or not words:
        return None
    toks = [_norm_token(w.get("text", "")) for w in words[sentence["w0"]:sentence["w1"] + 1]]
    want = [t for t in (_norm_token(x) for x in str(text).split()) if t]
    if not want or not toks:
        return None
    n = len(want)
    for i in range(0, len(toks) - n + 1):
        if toks[i:i + n] == want:
            return sentence["w0"] + i, sentence["w0"] + i + n - 1
    if n < 3:
        return None
    m = difflib.SequenceMatcher(None, toks, want, autojunk=False).find_longest_match(0, len(toks), 0, n)
    if m.size >= max(2, n - 1):
        return sentence["w0"] + m.a, sentence["w0"] + m.a + m.size - 1
    return None


def _register_trims(raw_trims, d: dict, ctx: dict, source: str = "critic") -> list[dict]:
    """Локальные дефекты, найденные ИИ (обрывок, паразитная фраза): фразы для ВЫРЕЗА вместо отсева ролика.

    Фраза ищется внутри указанного предложения; слишком большой вырез (больше 60% предложения и больше 6 слов)
    не принимается. Принятые вырезы лежат в d['forced_cuts'] и применяются при чистке слов."""
    words = ctx.get("words") or []
    sentences, id_index = ctx["sentences"], ctx["id_index"]
    known = {(c["w0"], c["w1"]) for c in d.get("forced_cuts") or []}
    added: list[dict] = []
    for t in raw_trims or []:
        if not isinstance(t, dict):
            continue
        i = id_index.get(str(t.get("sentence", "")).strip().upper())
        text = str(t.get("text", "")).strip()
        if i is None or not text or not words:
            continue
        sent = sentences[i]
        loc = _locate_phrase(sent, words, text)
        if loc is None:
            d.setdefault("trim_misses", []).append({"sentence": sent["id"], "text": text, "why": "фраза не найдена"})
            continue
        w0, w1 = loc
        span, total = w1 - w0 + 1, sent["w1"] - sent["w0"] + 1
        if span > 6 and span > MAX_FORCED_SHARE * 2 * total:
            d.setdefault("trim_misses", []).append({"sentence": sent["id"], "text": text, "why": "слишком большой вырез"})
            continue
        if (w0, w1) in known:
            continue
        known.add((w0, w1))
        entry = {"sentence": sent["id"], "w0": w0, "w1": w1, "source": source,
                 "text": " ".join(str(words[k].get("text", "")) for k in range(w0, w1 + 1)),
                 "reason": str(t.get("reason", "")).strip()}
        d.setdefault("forced_cuts", []).append(entry)
        added.append(entry)
    return added


def _parse_verdict(v: dict, d: dict, ctx: dict) -> tuple[dict, list[dict]]:
    scores = v.get("scores") or {}

    def score(key):
        try:
            return int(scores.get(key, 0))
        except (TypeError, ValueError):
            return 0

    by_index = {}
    for x in v.get("seams") or []:
        try:
            by_index[int(x.get("seam"))] = x
        except (TypeError, ValueError, AttributeError):
            continue
    seam_info = []
    for sm in _seams(d["pieces"], ctx["sentences"]):
        x = by_index.get(sm["index"])
        verdict = x.get("verdict") if x else None
        seam_info.append(dict(sm, verdict=verdict if verdict in ("ok", "jump") else "jump",
                              note=str(x.get("note", "")) if x else "критик не оценил стык"))
    trims = _register_trims(v.get("trims"), d, ctx, "critic")
    if trims:
        # локальный дефект на стыке (обрывок) снимается вырезом: такой стык больше не jump
        cut_sentences = {t["sentence"] for t in d.get("forced_cuts") or []}
        for si in seam_info:
            if si["verdict"] != "ok" and ({si["from_sentence"], si["to_sentence"]} & cut_sentences):
                si["verdict"] = "ok"
                si["note"] = (si["note"] + " " if si["note"] else "") + "(локальный дефект снят вырезом)"
        v = dict(v, seams_ok=True)
    seams_ok = all(si["verdict"] == "ok" for si in seam_info) and v.get("seams_ok") is not False
    critic = {
        "verdict": v.get("verdict"),
        "hook_strength": score("hook_strength"), "completeness": score("completeness"),
        "clarity": score("clarity"), "standalone": score("standalone"), "single_idea": score("single_idea"),
        "seams_ok": seams_ok,
        "seams": [{"index": si["index"], "verdict": si["verdict"], "note": si["note"]} for si in seam_info],
        "problems": [str(x) for x in v.get("problems") or []],
    }
    if trims:
        critic["trims"] = [{"sentence": t["sentence"], "text": t["text"]} for t in trims]
    return critic, seam_info


def _critique_round(drafts: list[dict], ctx: dict, round_no: int) -> list[tuple[dict, str]]:
    """Раунд критика пакетами по CRITIC_BATCH роликов."""
    batches = [drafts[i:i + CRITIC_BATCH] for i in range(0, len(drafts), CRITIC_BATCH)]
    workers = int((ctx["options"] or {}).get("parallel", 1) or 1)
    results = _run_batches(lambda arg: _critique_batch(arg[1], ctx, round_no, arg[0]), list(enumerate(batches, 1)), workers)
    return [item for batch in results for item in batch]


def _critique_batch(drafts: list[dict], ctx: dict, round_no: int, batch_no: int = 1) -> list[tuple[dict, str]]:
    """Один запрос критика. Исходы: pass | fixed | reject (fixed — пересобран по правке, нужен раунд 2)."""
    work_dir = ctx["work_dir"]
    blocks = [_critique_block(n, d, ctx, round_no) for n, d in enumerate(drafts, 1)]
    task = "critique" if round_no == 1 else f"critique_{round_no}"
    if batch_no > 1:
        task += f"_b{batch_no}"
    raw_name = "editorial_critique_raw" + ("" if round_no == 1 else f"_{round_no}") + ("" if batch_no == 1 else f"_b{batch_no}")
    try:
        data = _call(ctx["llm"], ctx["provider"],
                     _critique_prompt("\n\n".join(blocks), min_d=ctx["min_d"], max_d=ctx["max_d"], round_no=round_no),
                     CRITIQUE_SCHEMA, work_dir, task)
    except Exception as exc:
        if round_no > 1:  # без второго раунда ролик идёт в ремонт как «почти прошёл», а не в отсев
            for d in drafts:
                d["soft"] = True
                d.setdefault("round1_problems", []).append(f"второй раунд критика недоступен: {exc}")
            return [(d, "pass") for d in drafts]
        if round_no == 1:  # деградация: без критика ролики остаются как есть
            for d in drafts:
                d["critic"] = {"verdict": "pass", "hook_strength": 0, "completeness": 0, "clarity": 0,
                               "standalone": 0, "single_idea": 0, "seams_ok": True, "seams": [],
                               "problems": [f"критик недоступен: {exc}"], "unavailable": True}
            return [(d, "pass") for d in drafts]
    _write_json(work_dir / f"{raw_name}.json", data)
    verdicts = {}
    for v in data.get("verdicts") or []:
        try:
            verdicts[int(v.get("clip"))] = v
        except (TypeError, ValueError):
            continue
    out = []
    for n, d in enumerate(drafts, 1):
        v = verdicts.get(n)
        title = d["raw"].get("title", "")
        stage = f"critic_round{round_no}"
        if v is None:
            _log_drop(ctx, title, stage, "критик не вернул вердикт", draft=d)
            out.append((d, "reject"))
            continue
        critic, seam_info = _parse_verdict(v, d, ctx)
        d.setdefault("rounds", []).append(critic)
        d["seams_info"] = seam_info
        verdict = critic["verdict"]
        hard = _hard_score_defects(critic)
        if hard:  # явный дефект: оценка <= 4 (в т.ч. нет вывода: completeness <= 4)
            _log_drop(ctx, title, stage, "явный дефект: " + ", ".join(hard) + (
                "; " + "; ".join(critic["problems"][:2]) if critic["problems"] else ""), critic, draft=d)
            out.append((d, "reject"))
        elif verdict == "fix" and round_no < MAX_CRITIC_ROUNDS:
            fixed = _apply_fix(v, d, ctx)
            d["round1_problems"] = list(critic["problems"]) + [
                f"стык {si['index']} был jump: {si['note']}" for si in seam_info if si["verdict"] != "ok"]
            if fixed is None:
                # правка неприменима: ролик остаётся как есть и уходит в ремонт (раунд 3), а не в отсев
                d["soft"] = True
                d["round1_problems"].append("правка критика неприменима (недопустимые id, длительность или области)")
                out.append((d, "pass"))
                continue
            d["pieces"] = fixed
            _refresh_hints(d, ctx)
            out.append((d, "fixed"))
        else:
            # pass, либо fix/reject без жёсткого дефекта: «почти прошёл» — не отсев, а кандидат на ремонт
            if verdict != "pass":
                d["soft"] = True
            out.append((d, "pass"))
    return out


def _hard_score_defects(critic: dict) -> list[str]:
    return [f"{k} {int(critic.get(k, 0))}<={HARD_SCORE_MAX}" for k in CONTENT_SCORES
            if int(critic.get(k, 0)) <= HARD_SCORE_MAX]


def _near_miss(critic: dict | None, d: dict | None = None) -> bool:
    """Ролик «почти прошёл»: любая из оценок ниже 7, непройденный стык или нестрогий вердикт критика."""
    critic = critic or {}
    if critic.get("unavailable"):
        return False
    if any(int(critic.get(k, 0)) < NEAR_MISS_BELOW for k in ALL_SCORES):
        return True
    return not critic.get("seams_ok", True) or bool(d and d.get("soft"))


def _finalize_critic(d: dict, fixed: bool, ctx: dict) -> None:
    last = dict(d["rounds"][-1]) if d.get("rounds") else {}
    limit = int(((ctx["options"] or {}).get("min_critic_scores") or {}).get("hook_strength", HOOK_WARN_BELOW))
    last["hook_warning"] = bool(int(last.get("hook_strength", 0)) < limit or _hook_hint(d["pieces"], ctx["sentences"]))
    last["verdict"] = "fix" if fixed else "pass"
    last["rounds"] = [dict(r) for r in d.get("rounds", [])]
    if _payoff_hint(d["pieces"]):
        last.setdefault("problems", []).append(_payoff_hint(d["pieces"]))
    d["critic"] = last


def _critique(drafts: list[dict], ctx: dict) -> list[dict]:
    """Раунды 1–2. Отсев только за явные дефекты; остальные (в т.ч. с оценками 5–6) идут дальше."""
    if not drafts:
        return []
    survivors: list[dict] = []
    pending = []
    for d, outcome in _critique_round(drafts, ctx, 1):
        if outcome == "pass":
            if not d.get("critic", {}).get("unavailable"):
                _finalize_critic(d, fixed=False, ctx=ctx)
            survivors.append(d)
        elif outcome == "fixed":
            pending.append(d)
    if pending:
        for d, outcome in _critique_round(pending, ctx, 2):
            if outcome == "pass":
                _finalize_critic(d, fixed=True, ctx=ctx)
                survivors.append(d)
    survivors.sort(key=lambda d: drafts.index(d))
    return survivors


